/* ============================================================================
   Anovo - Auditoria por disparador  (Firebird)
   ----------------------------------------------------------------------------
   Reemplaza a los 48 bloques de auditoria que vivian dentro de los
   procedimientos almacenados. La garantia es la misma -la impone la base, no el
   codigo- pero no obliga a sacar toda la escritura de la aplicacion.

   El disparador no conoce al usuario de la aplicacion, solo al de la conexion.
   El usuario viaja en el contexto de sesion, que la aplicacion fija al abrir la
   transaccion:

     RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID', :id)

   Si el contexto viene vacio la operacion FALLA. No se audita como anonima: una
   escritura sin usuario identificado es un error de programacion, y dejarla
   pasar convierte la auditoria en decorativa.

   El sitio para fijar el contexto es el middleware o el arranque de la
   transaccion en el repositorio. Si depende de que alguien se acuerde en cada
   servicio, vuelve a ser una convencion.
   ============================================================================ */

CREATE EXCEPTION E_AUDITORIA_SIN_USUARIO
  'No hay USUARIO_ID en el contexto de sesion: toda escritura debe identificar al usuario.';

SET TERM ^ ;

/* --- USUARIOS ------------------------------------------------------------ */
CREATE TRIGGER TR_USUARIOS_AUD FOR USUARIOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  IF (INSERTING) THEN BEGIN V_ACCION = 'insertar';   V_ID = NEW.ID; END
  ELSE IF (UPDATING) THEN BEGIN V_ACCION = 'actualizar'; V_ID = NEW.ID; END
  ELSE BEGIN V_ACCION = 'borrar'; V_ID = OLD.ID; END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID)
  VALUES (:V_USUARIO, :V_ACCION, 'USUARIOS', :V_ID);
END^

