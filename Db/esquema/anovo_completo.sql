   ----------------------------------------------------------------------------
   AUDITORIA.DETALLE quedaba nulo en casi todo: el disparador sabe que cambio
   una fila, pero no por que. Quien si lo sabe es el servicio, que conoce la
   intencion -una edicion de datos, una revocacion de consentimiento-.

