  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COTIZACION_ID   INTEGER NOT NULL REFERENCES COTIZACIONES(ID) ON DELETE CASCADE,
  TIPO            VARCHAR(10) NOT NULL,
  MATERIAL_ID     INTEGER REFERENCES MATERIALES(ID),
  MANO_OBRA_ID    INTEGER REFERENCES MANO_OBRA(ID),
  MAQUINA_ID      INTEGER REFERENCES MAQUINAS(ID),
  DESCRIPCION     D_DESCRIPCION NOT NULL,
  UNIDAD_MEDIDA   VARCHAR(20),
  CANTIDAD        D_CANTIDAD,
  PRECIO_UNITARIO D_MONTO,
  SUBTOTAL        D_MONTO,
  ORDEN           SMALLINT DEFAULT 0 NOT NULL,
  CONSTRAINT CK_DETALLE_TIPO CHECK (
    (TIPO = 'material'  AND MATERIAL_ID  IS NOT NULL AND MANO_OBRA_ID IS NULL AND MAQUINA_ID IS NULL) OR
    (TIPO = 'mano_obra' AND MANO_OBRA_ID IS NOT NULL AND MATERIAL_ID  IS NULL AND MAQUINA_ID IS NULL) OR
    (TIPO = 'maquina'   AND MAQUINA_ID   IS NOT NULL AND MATERIAL_ID  IS NULL AND MANO_OBRA_ID IS NULL) OR
    (TIPO = 'nota'      AND MATERIAL_ID  IS NULL AND MANO_OBRA_ID IS NULL AND MAQUINA_ID IS NULL)
  )
);

CREATE INDEX IDX_DETALLE_COTIZ ON COTIZACION_DETALLE (COTIZACION_ID);

