  PORCENTAJE_AJUSTE   NUMERIC(5,2) DEFAULT 0 NOT NULL,
  MOTIVO_AJUSTE       D_DESCRIPCION,
  PORCENTAJE_IVA      NUMERIC(5,2) DEFAULT 0 NOT NULL,
  MONTO_IMPUESTO      D_MONTO,
  MONTO_TOTAL         D_MONTO,
  MOTIVO_RECHAZO      D_DESCRIPCION,
