CREATE INDEX IDX_CONSHIST_CLIENTE ON CLIENTE_CONSENTIMIENTO_HISTORIAL (CLIENTE_ID);

/* ============================================================================
   4. SOLICITUDES  (suben desde el movil)
   ============================================================================ */
CREATE TABLE SOLICITUDES (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL         D_UUID NOT NULL UNIQUE,
  CLIENTE_ID         INTEGER NOT NULL REFERENCES CLIENTES(ID),
  ASESOR_ID          INTEGER NOT NULL REFERENCES USUARIOS(ID),
  DESCRIPCION        D_DESCRIPCION NOT NULL,
  OBSERVACIONES      D_DESCRIPCION,
  /* Distintas a proposito: entre una y otra pueden pasar horas si el asesor
     estuvo sin cobertura. Confundirlas falsea los reportes de tiempo. */
  FECHA_CAPTURA      TIMESTAMP NOT NULL,
  FECHA_RECEPCION    D_TIMESTAMP,
  ESTADO             D_ESTADO NOT NULL,
  FECHA_MODIFICACION D_TIMESTAMP,
  OBJVERSION         D_VERSION
);

CREATE INDEX IDX_SOLICITUDES_ASESOR  ON SOLICITUDES (ASESOR_ID);
CREATE INDEX IDX_SOLICITUDES_CLIENTE ON SOLICITUDES (CLIENTE_ID);

/* Croquis: el JSON de trazos va en CONTENIDO_JSON. La imagen es opcional para
   croquis y obligatoria de hecho para fotos. */
CREATE TABLE SOLICITUD_ADJUNTOS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOLICITUD_ID   INTEGER NOT NULL REFERENCES SOLICITUDES(ID),
  UUID_LOCAL     D_UUID NOT NULL UNIQUE,
  TIPO           VARCHAR(10) NOT NULL,
  NOMBRE_ARCHIVO D_NOMBRE,
  MIME           VARCHAR(40),
  TAMANO_BYTES   INTEGER,
  /* El BLOB vive fuera de la fila: un SELECT que no pida CONTENIDO no toca los
     bytes. Listar adjuntos es igual de rapido con 50 fotos que con 5. */
  CONTENIDO      BLOB SUB_TYPE BINARY,
  CONTENIDO_JSON BLOB SUB_TYPE TEXT,
  ACTIVO         D_BOOLEANO,
  FECHA_CREACION D_TIMESTAMP,
  OBJVERSION     D_VERSION,
  CONSTRAINT CK_ADJUNTO_TAMANO CHECK (TAMANO_BYTES <= 3145728),
  CONSTRAINT CK_ADJUNTO_TIPO   CHECK (TIPO IN ('croquis','foto'))
);

CREATE INDEX IDX_ADJUNTOS_SOLICITUD ON SOLICITUD_ADJUNTOS (SOLICITUD_ID);

/* Una fila por medicion. Reemplaza LARGO/ANCHO/ALTO fijos: una pieza puede
   llevar varias. ETIQUETA correlaciona con un punto del croquis, no es unica. */
CREATE TABLE SOLICITUD_MEDIDAS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL     D_UUID UNIQUE,
  SOLICITUD_ID   INTEGER NOT NULL REFERENCES SOLICITUDES(ID),
  CROQUIS_ID     INTEGER REFERENCES SOLICITUD_ADJUNTOS(ID),
  ETIQUETA       VARCHAR(5),
  TIPO_MEDIDA    VARCHAR(30) NOT NULL,
  VALOR          D_CANTIDAD,
  UNIDAD_MEDIDA  VARCHAR(10) DEFAULT 'cm' NOT NULL,
  OBSERVACION    D_DESCRIPCION,
  ORDEN          SMALLINT DEFAULT 0 NOT NULL,
  FECHA_CREACION D_TIMESTAMP,
  OBJVERSION     D_VERSION
);

CREATE INDEX IDX_MEDIDAS_SOLICITUD ON SOLICITUD_MEDIDAS (SOLICITUD_ID);

