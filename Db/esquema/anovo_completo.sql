/* ============================================================================
   DOMINIOS
   ============================================================================ */
CREATE DOMAIN D_MONTO       AS NUMERIC(15,2) DEFAULT 0 NOT NULL;
CREATE DOMAIN D_CANTIDAD    AS NUMERIC(12,3) DEFAULT 0 NOT NULL;
CREATE DOMAIN D_NOMBRE      AS VARCHAR(120);
CREATE DOMAIN D_DESCRIPCION AS VARCHAR(500);
CREATE DOMAIN D_ESTADO      AS VARCHAR(20);
CREATE DOMAIN D_UUID        AS VARCHAR(36);
CREATE DOMAIN D_BOOLEANO    AS BOOLEAN DEFAULT TRUE NOT NULL;
CREATE DOMAIN D_TIMESTAMP   AS TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL;
/* foVersion de DMVC. La mantiene el framework dentro del UPDATE, sin
   disparador: uno que la tocara pelearia con el. */
CREATE DOMAIN D_VERSION     AS INTEGER DEFAULT 0 NOT NULL;

/* ============================================================================
   1. AUDITORIA
   La escribe el disparador, no la aplicacion. El usuario del backend no tiene
   permiso aqui: ver 04_usuario.sql.
   ============================================================================ */
CREATE TABLE AUDITORIA (
  ID          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID  INTEGER,
  ACCION      VARCHAR(50)  NOT NULL,
  ENTIDAD     VARCHAR(50)  NOT NULL,
  ENTIDAD_ID  INTEGER,
  DETALLE     D_DESCRIPCION,
  FECHA       D_TIMESTAMP
);

CREATE INDEX IDX_AUDITORIA_FECHA   ON AUDITORIA (FECHA);
CREATE INDEX IDX_AUDITORIA_ENTIDAD ON AUDITORIA (ENTIDAD, ENTIDAD_ID);

/* ============================================================================
   2. USUARIOS Y ROLES
   ============================================================================ */
CREATE TABLE ROLES (
  ID     INTEGER PRIMARY KEY,
  CODIGO VARCHAR(20) NOT NULL UNIQUE,
  NOMBRE D_NOMBRE NOT NULL
);

CREATE TABLE USUARIOS (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CORREO             VARCHAR(150) NOT NULL UNIQUE,
  NOMBRE             D_NOMBRE NOT NULL,
  ROL_ID             INTEGER NOT NULL REFERENCES ROLES(ID),
  ACTIVO             D_BOOLEANO,
  DEBE_CAMBIAR_CLAVE D_BOOLEANO DEFAULT FALSE NOT NULL,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP
);

CREATE TABLE USUARIOS_CLAVES (
  ID           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID   INTEGER NOT NULL REFERENCES USUARIOS(ID),
  CLAVE_HASH   VARCHAR(255) NOT NULL,
  ACTIVO       D_BOOLEANO,
  FECHA_CAMBIO D_TIMESTAMP
);

CREATE INDEX IDX_CLAVES_USUARIO_ACTIVO ON USUARIOS_CLAVES (USUARIO_ID, ACTIVO);

CREATE TABLE EMPRESA (
  ID                  INTEGER PRIMARY KEY,
  RAZON_SOCIAL        D_NOMBRE NOT NULL,
  CEDULA_JURIDICA     VARCHAR(20) NOT NULL UNIQUE,
  DIRECCION           D_DESCRIPCION,
  TELEFONO_FIJO       VARCHAR(30),
  CELULAR             VARCHAR(30),
  CORREO              VARCHAR(150),
  REPRESENTANTE_LEGAL D_NOMBRE,
  CUENTA_BANCARIA     VARCHAR(60),
  MODIFICADO_POR      INTEGER REFERENCES USUARIOS(ID),
  FECHA_MODIFICACION  D_TIMESTAMP
);

/* ============================================================================
   3. CLIENTES
   Datos personales: aplica Ley 8968. No exponerlos por RQL abierto.
   ============================================================================ */
CREATE TABLE CLIENTES (
  ID                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL             D_UUID UNIQUE,
  NOMBRE                 D_NOMBRE NOT NULL,
  IDENTIFICACION         VARCHAR(30),
  TELEFONO               VARCHAR(30),
  CORREO                 VARCHAR(150),
  DIRECCION              D_DESCRIPCION,
  LATITUD                NUMERIC(9,6),
  LONGITUD               NUMERIC(9,6),
  ACTIVO                 D_BOOLEANO,
  EXONERADO              D_BOOLEANO DEFAULT FALSE NOT NULL,
  CODIGO_EXONERACION     VARCHAR(30),
  CONSENTIMIENTO_ESTADO  D_ESTADO DEFAULT 'pendiente' NOT NULL,
  CONSENTIMIENTO_FECHA   TIMESTAMP,
  CONSENTIMIENTO_VERSION VARCHAR(10),
  ANONIMIZADO            D_BOOLEANO DEFAULT FALSE NOT NULL,
  FECHA_CREACION         D_TIMESTAMP,
  FECHA_MODIFICACION     D_TIMESTAMP,
  OBJVERSION             D_VERSION,
  CONSTRAINT CK_CLIENTES_EXONERACION CHECK (EXONERADO = FALSE OR CODIGO_EXONERACION IS NOT NULL),
  CONSTRAINT CK_CLIENTES_CONS_ESTADO CHECK (CONSENTIMIENTO_ESTADO IN ('pendiente','firmado','revocado'))
);

CREATE TABLE CLIENTE_CONTACTOS (
  ID                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL             D_UUID UNIQUE,
  CLIENTE_ID             INTEGER NOT NULL REFERENCES CLIENTES(ID),
  NOMBRE                 D_NOMBRE NOT NULL,
  AREA                   VARCHAR(80),
  TELEFONO               VARCHAR(30),
  CORREO                 VARCHAR(150),
  PRINCIPAL              D_BOOLEANO DEFAULT FALSE NOT NULL,
  CONSENTIMIENTO_ESTADO  D_ESTADO DEFAULT 'pendiente' NOT NULL,
  CONSENTIMIENTO_FECHA   TIMESTAMP,
  CONSENTIMIENTO_VERSION VARCHAR(10),
  ANONIMIZADO            D_BOOLEANO DEFAULT FALSE NOT NULL,
  ACTIVO                 D_BOOLEANO,
  FECHA_CREACION         D_TIMESTAMP,
  OBJVERSION             D_VERSION,
  CONSTRAINT CK_CONTACTOS_CONS_ESTADO CHECK (CONSENTIMIENTO_ESTADO IN ('pendiente','firmado','revocado'))
);

CREATE INDEX IDX_CONTACTOS_CLIENTE ON CLIENTE_CONTACTOS (CLIENTE_ID);

/* Fuente de verdad del consentimiento, solo agrega filas. Aqui vive la
   evidencia de la firma; las columnas de CLIENTES son cache del estado. */
CREATE TABLE CLIENTE_CONSENTIMIENTO_HISTORIAL (
  ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CLIENTE_ID              INTEGER NOT NULL REFERENCES CLIENTES(ID),
  CLIENTE_CONTACTO_ID     INTEGER REFERENCES CLIENTE_CONTACTOS(ID),
  ACCION                  VARCHAR(20) NOT NULL,
  VERSION_TEXTO           VARCHAR(10) NOT NULL,
  FECHA                   D_TIMESTAMP,
  FIRMANTE_NOMBRE         D_NOMBRE,
  FIRMANTE_IDENTIFICACION VARCHAR(30),
  FIRMA_IMAGEN            BLOB SUB_TYPE BINARY,
  FIRMA_MIME              VARCHAR(40),
  ORIGEN                  VARCHAR(20),
  CONSTRAINT CK_CONSHIST_ACCION CHECK (ACCION IN ('otorgado','revocado'))
