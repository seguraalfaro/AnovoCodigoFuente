CREATE TRIGGER TR_SOLICITUDES_BU FOR SOLICITUDES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_MATERIALES_BU FOR MATERIALES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_MANO_OBRA_BU FOR MANO_OBRA ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_MAQUINAS_BU FOR MAQUINAS ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_EMPRESA_BU FOR EMPRESA ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_COTIZACIONES_BU FOR COTIZACIONES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

SET TERM ; ^

COMMIT;

