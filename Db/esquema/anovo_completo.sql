/* ============================================================================
   anovo_completo.sql
   Firebird 4.0 - base ANOVO

   La base entera desde cero, en el estado que dejo la ultima migracion. Es la
   suma de migraciones\01 a 20 en orden de aplicacion; cada tramo conserva la
   cabecera de su script para saber de donde salio. La 12 no tiene tramo
   propio: su cambio ya esta en la tabla MANO_OBRA del tramo 01.

   Al agregar una migracion nueva, sumarla tambien aqui al final.

   Antes de correrlo:
     - crear la base vacia con DEFAULT CHARACTER SET UTF8 y conectarse a ella;
     - sustituir CLAVE_PENDIENTE en el tramo 04 por la clave de ANOVO_BACKEND.
       CREATE USER es del servidor: si el usuario ya existe, quitar esas lineas;
     - el tramo 02 trae datos de prueba (bloque B). No va en produccion.

   Despues de correrlo, la base queda completa y sin que nadie pueda entrar:
   CLAVE_HASH sale con el marcador PENDIENTE-REGENERAR, porque una clave real
   no viaja en el repositorio. Para una base de trabajo hay que seguir con:

     datos-prueba\claves_prueba.sql   pone Anovo2026 a los ocho de prueba
     datos-prueba\carga_demo.sql      clientes, catalogos, solicitudes

   En produccion no se corre ninguno de los dos: las claves se asignan una por
   una y se cambian en el primer ingreso.

   El orden no es el de los nombres de tramo: 02 va antes de 03 porque los
   disparadores de auditoria exigen usuario en contexto y un script no lo tiene.
   ============================================================================ */


