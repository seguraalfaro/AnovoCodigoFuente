/* ============================================================================
   8. DISPARADORES de FECHA_MODIFICACION
   BEFORE UPDATE: se asigna sobre NEW, sin segundo UPDATE y sin recursion.
   En SQL Server esto necesitaba guarda anti-recursion; aqui no.
   ============================================================================ */
