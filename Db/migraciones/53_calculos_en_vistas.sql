/* ============================================================================
   Anovo - Migracion 53: todos los calculos de dashboards y reportes en vistas
   ----------------------------------------------------------------------------
   Lo que la migracion 52 dejo en el servicio (grupos, tasa de aprobacion, la
   mas antigua, sin respuesta fuera de plazo) y todas las sumas de los reportes
   pasan a la base (19/10/2026). El backend solo lee filas y las copia al DTO.

   Tasas y porcentajes en NUMERIC(5,2): 62.50 y no 62 ni 63. Los montos siguen
   en NUMERIC(18,2).

   Los reportes dependen del rango que se elige en pantalla. Como una vista no
   recibe parametros, el repositorio fija antes de leer tres variables de la
   sesion, igual que la auditoria:
     REPORTE_DESDE    fecha inicial (AAAA-MM-DD)
     REPORTE_HASTA    fecha final, incluida (AAAA-MM-DD)
     REPORTE_USUARIO  0 = todo; un id = solo lo que capturo o elaboro

   Dashboards:
   - V_DASH_ASESOR_GRUPOS: solicitudes del asesor por grupo, en orden.
   - V_DASH_ASESOR_RESUMEN: la mas antigua esperando, tasa y mes anterior.
   - V_DASH_ETAPAS_USUARIO: las cinco etapas de cada usuario, con cero.
   - V_DASH_ASISTENTE_RESUMEN: devueltas, sin respuesta, la mas antigua de la
     cola y los pasos del mes con su tasa.
   - V_DASH_SUPERVISOR_RESUMEN: pasos del equipo del mes, tasa y monto del mes
     anterior.
   - V_RESUMEN_MES: suma la tasa de aprobacion del mes (gerencia).

   Reportes:
   - V_REPORTE_PERIODO: el periodo elegido y el anterior.
   - V_REPORTE_DIA: los pasos de cada dia de los dos periodos, ya filtrados.
   - V_REPORTE_RESUMEN, V_REPORTE_ESTADO, V_REPORTE_ASESOR, V_REPORTE_TIPO,
     V_REPORTE_MES (sin huecos) y V_REPORTE_CLIENTE.

   No crea tablas ni toca datos. Todo en ASCII.
   ============================================================================ */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 53: calculos de dashboards y reportes en vistas') FROM RDB$DATABASE;

CREATE VIEW V_DASH_ASESOR_GRUPOS AS
SELECT ASESOR_ID, GRUPO,
       CAST(CASE GRUPO WHEN 'esperando' THEN 1 WHEN 'elaboracion' THEN 2
                       WHEN 'enviada' THEN 3 WHEN 'aprobada' THEN 4
                       WHEN 'rechazada' THEN 5 ELSE 6 END AS INTEGER) AS ORDEN,
       CAST(SUM(CANTIDAD) AS INTEGER) AS CANTIDAD,
       CAST(MAX(DIAS_MAS_ANTIGUA) AS INTEGER) AS DIAS_MAS_ANTIGUA
  FROM (SELECT ASESOR_ID, CANTIDAD, DIAS_MAS_ANTIGUA,
               CAST(CASE
                 WHEN ESTADO = 'descartada' AND CON_COTIZACION
                   THEN 'sin_respuesta'
                 WHEN ESTADO IN ('borrador', 'pendiente', 'devuelta',
                                 'visto_bueno') THEN 'elaboracion'
                 WHEN ESTADO = 'enviada' THEN 'enviada'
                 WHEN ESTADO = 'aprobada' THEN 'aprobada'
                 WHEN ESTADO IN ('rechazada', 'descartada') THEN 'rechazada'
                 ELSE 'esperando' END AS VARCHAR(15)) AS GRUPO
          FROM V_DASH_ESTADO_ASESOR)
 GROUP BY ASESOR_ID, GRUPO;

CREATE VIEW V_DASH_ASESOR_RESUMEN AS
SELECT G.ASESOR_ID,
       CAST(COALESCE(MAX(CASE WHEN G.GRUPO = 'esperando'
            THEN G.DIAS_MAS_ANTIGUA END), 0) AS INTEGER) AS DIAS_MAS_ANTIGUA,
       CAST(COALESCE(SUM(CASE WHEN G.GRUPO = 'aprobada' THEN G.CANTIDAD END)
            * 100.0000 / NULLIF(SUM(CASE WHEN G.GRUPO IN ('aprobada',
            'rechazada') THEN G.CANTIDAD END), 0), 0) AS NUMERIC(5,2))
         AS TASA_APROBACION,
       (SELECT CAST(COALESCE(SUM(M.CANTIDAD), 0) AS INTEGER)
          FROM V_DASH_SOLICITUDES_MES M
         WHERE M.ASESOR_ID = G.ASESOR_ID
           AND M.ANIO = EXTRACT(YEAR FROM DATEADD(-1 MONTH TO CURRENT_DATE))
           AND M.MES = EXTRACT(MONTH FROM DATEADD(-1 MONTH TO CURRENT_DATE)))
         AS SOLICITUDES_MES_ANTERIOR
  FROM V_DASH_ASESOR_GRUPOS G
 GROUP BY G.ASESOR_ID;

CREATE VIEW V_DASH_ETAPAS_USUARIO AS
SELECT U.ID AS USUARIO_ID, E.ESTADO, E.ORDEN,
       CAST(COALESCE(D.CANTIDAD, 0) AS INTEGER) AS CANTIDAD
  FROM USUARIOS U
 CROSS JOIN (SELECT CAST('borrador' AS VARCHAR(15)) AS ESTADO, 1 AS ORDEN
               FROM RDB$DATABASE
             UNION ALL SELECT 'pendiente', 2 FROM RDB$DATABASE
             UNION ALL SELECT 'devuelta', 3 FROM RDB$DATABASE
             UNION ALL SELECT 'visto_bueno', 4 FROM RDB$DATABASE
             UNION ALL SELECT 'enviada', 5 FROM RDB$DATABASE) E
  LEFT JOIN V_DASH_ETAPAS D ON D.ELABORADA_POR = U.ID AND D.ESTADO = E.ESTADO;

CREATE VIEW V_DASH_ASISTENTE_RESUMEN AS
SELECT U.ID AS USUARIO_ID,
       (SELECT CAST(COALESCE(MAX(S.DIAS_ESPERA), 0) AS INTEGER)
          FROM V_SOLICITUDES S
         WHERE S.ESTADO = 'recibida' AND S.TIENE_COTIZACION = FALSE)
         AS DIAS_MAS_ANTIGUA,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACIONES C
         WHERE C.ELABORADA_POR = U.ID AND C.ESTADO = 'devuelta')
         AS DEVUELTAS,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM V_DASH_ENVIADAS V
         WHERE V.ELABORADA_POR = U.ID
           AND V.DIAS > COALESCE(V.DIAS_SIN_RESPUESTA, 0))
         AS SIN_RESPUESTA,
       CAST(COALESCE(P.PRESENTADAS, 0) AS INTEGER) AS PRESENTADAS_MES,
       CAST(COALESCE(P.APROBADAS, 0) AS INTEGER) AS APROBADAS_MES,
       CAST(COALESCE(P.RECHAZADAS, 0) AS INTEGER) AS RECHAZADAS_MES,
       CAST(COALESCE(P.MONTO_APROBADO, 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO_MES,
       CAST(COALESCE(P.APROBADAS * 100.0000
            / NULLIF(P.APROBADAS + P.RECHAZADAS, 0), 0) AS NUMERIC(5,2))
         AS TASA_MES
  FROM USUARIOS U
  LEFT JOIN V_DASH_PASOS_MES P
    ON P.ELABORADA_POR = U.ID
   AND P.ANIO = EXTRACT(YEAR FROM CURRENT_DATE)
   AND P.MES = EXTRACT(MONTH FROM CURRENT_DATE);

CREATE VIEW V_DASH_SUPERVISOR_RESUMEN AS
SELECT CAST(COALESCE(A.VISTO_BUENO, 0) AS INTEGER) AS VISTO_BUENO_MES,
       CAST(COALESCE(A.DEVUELTAS, 0) AS INTEGER) AS DEVUELTAS_MES,
       CAST(COALESCE(A.APROBADAS, 0) AS INTEGER) AS APROBADAS_MES,
       CAST(COALESCE(A.RECHAZADAS, 0) AS INTEGER) AS RECHAZADAS_MES,
       CAST(COALESCE(A.MONTO_APROBADO, 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO_MES,
       CAST(COALESCE(A.APROBADAS * 100.0000
            / NULLIF(A.APROBADAS + A.RECHAZADAS, 0), 0) AS NUMERIC(5,2))
         AS TASA_APROBACION,
       CAST(COALESCE(B.MONTO_APROBADO, 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO_ANTERIOR
  FROM RDB$DATABASE
  LEFT JOIN V_DASH_PASOS_EQUIPO A
    ON A.ANIO = EXTRACT(YEAR FROM CURRENT_DATE)
   AND A.MES = EXTRACT(MONTH FROM CURRENT_DATE)
  LEFT JOIN V_DASH_PASOS_EQUIPO B
    ON B.ANIO = EXTRACT(YEAR FROM DATEADD(-1 MONTH TO CURRENT_DATE))
   AND B.MES = EXTRACT(MONTH FROM DATEADD(-1 MONTH TO CURRENT_DATE));

CREATE OR ALTER VIEW V_RESUMEN_MES AS
SELECT R.*,
       CAST(COALESCE(R.APROBADAS_MES * 100.0000
            / NULLIF(R.APROBADAS_MES + R.RECHAZADAS_MES, 0), 0) AS NUMERIC(5,2))
         AS TASA_APROBACION
  FROM (SELECT P.MES_DESDE AS DESDE, P.MES_HASTA AS HASTA,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM COTIZACION_ESTADOS H JOIN COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'enviada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS COTIZADO_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACION_ESTADOS H
         WHERE H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS APROBADAS_MES,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM COTIZACION_ESTADOS H JOIN COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS MONTO_APROBADO_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACION_ESTADOS H
         WHERE H.ESTADO = 'rechazada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS RECHAZADAS_MES,
       (SELECT CAST(COALESCE(AVG(C.DIAS_RESPUESTA), 0) AS INTEGER)
          FROM COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'enviada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS RESPUESTA_MEDIA,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM USUARIOS U
          JOIN ROLES R ON R.ID = U.ROL_ID
         WHERE R.CODIGO = 'asesor' AND U.ACTIVO)
         AS ASESORES_ACTIVOS
  FROM V_PERIODO_ACTUAL P) R;

CREATE VIEW V_REPORTE_PERIODO AS
WITH P AS (
  SELECT CAST(RDB$GET_CONTEXT('USER_SESSION', 'REPORTE_DESDE') AS DATE)
           AS DESDE,
         CAST(RDB$GET_CONTEXT('USER_SESSION', 'REPORTE_HASTA') AS DATE)
           AS HASTA,
         CAST(COALESCE(RDB$GET_CONTEXT('USER_SESSION', 'REPORTE_USUARIO'),
           '0') AS INTEGER) AS USUARIO
    FROM RDB$DATABASE),
L AS (
  SELECT DESDE, HASTA, USUARIO,
         CAST((EXTRACT(YEAR FROM HASTA) * 12 + EXTRACT(MONTH FROM HASTA))
            - (EXTRACT(YEAR FROM DESDE) * 12 + EXTRACT(MONTH FROM DESDE)) + 1
            AS INTEGER) AS MESES,
         CAST(DATEDIFF(DAY FROM DESDE TO HASTA) AS INTEGER) AS DIAS
    FROM P)
SELECT CAST('actual' AS VARCHAR(8)) AS PERIODO, DESDE, HASTA, USUARIO
  FROM L
UNION ALL
SELECT 'anterior',
       CASE WHEN EXTRACT(DAY FROM DESDE) = 1
            THEN DATEADD(-MESES MONTH TO DESDE)
            ELSE DATEADD(-(DIAS + 1) DAY TO DESDE) END,
       CASE WHEN EXTRACT(DAY FROM DESDE) = 1
            THEN DATEADD(-MESES MONTH TO HASTA)
            ELSE DATEADD(-1 DAY TO DESDE) END,
       USUARIO
  FROM L;

CREATE VIEW V_REPORTE_DIA AS
SELECT P.PERIODO, D.FECHA, D.ANIO, D.MES, D.ESTADO, D.ASESOR_ID,
       D.ASESOR_NOMBRE, D.TIPO_TRABAJO_ID, D.TIPO_TRABAJO_NOMBRE,
       D.ELABORADA_POR, D.CANTIDAD, D.MONTO_TOTAL, D.APROBADAS, D.RECHAZADAS,
       D.MONTO_APROBADO, D.SUMA_DIAS_RESPUESTA, D.CON_RESPUESTA,
       CAST(CASE WHEN D.ESTADO = 'enviada' THEN D.CANTIDAD ELSE 0 END
            AS INTEGER) AS ENVIADAS,
       CAST(CASE WHEN D.ESTADO = 'enviada' THEN D.MONTO_TOTAL ELSE 0 END
            AS NUMERIC(18,2)) AS MONTO_ENVIADO,
       CAST(CASE WHEN D.ESTADO = 'descartada' THEN D.CANTIDAD ELSE 0 END
            AS INTEGER) AS DESCARTADAS,
       (D.ESTADO IN ('enviada', 'descartada') OR D.APROBADAS > 0
        OR D.RECHAZADAS > 0) AS DEL_CLIENTE
  FROM V_REPORTE_PERIODO P
  JOIN V_COTIZACIONES_DIA D
    ON D.FECHA BETWEEN P.DESDE AND P.HASTA
   AND (P.USUARIO = 0 OR D.ASESOR_ID = P.USUARIO
        OR D.ELABORADA_POR = P.USUARIO);

CREATE VIEW V_REPORTE_RESUMEN AS
SELECT P.PERIODO, P.DESDE, P.HASTA,
       CAST(COALESCE(SUM(R.ENVIADAS), 0) AS INTEGER) AS TOTAL,
       CAST(COALESCE(SUM(R.MONTO_ENVIADO), 0) AS NUMERIC(18,2)) AS MONTO_TOTAL,
       CAST(COALESCE(SUM(R.APROBADAS), 0) AS INTEGER) AS APROBADAS,
       CAST(COALESCE(SUM(R.MONTO_APROBADO), 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO,
       CAST(COALESCE(SUM(R.RECHAZADAS), 0) AS INTEGER) AS RECHAZADAS,
       CAST(COALESCE(SUM(R.DESCARTADAS), 0) AS INTEGER) AS DESCARTADAS,
       CAST(COALESCE(SUM(R.SUMA_DIAS_RESPUESTA)
            / NULLIF(SUM(R.CON_RESPUESTA), 0), 0) AS INTEGER)
         AS RESPUESTA_MEDIA,
       CAST(COALESCE(SUM(R.APROBADAS) * 100.0000
            / NULLIF(SUM(R.APROBADAS) + SUM(R.RECHAZADAS), 0), 0)
            AS NUMERIC(5,2)) AS TASA_APROBACION
  FROM V_REPORTE_PERIODO P
  LEFT JOIN V_REPORTE_DIA R ON R.PERIODO = P.PERIODO
 GROUP BY P.PERIODO, P.DESDE, P.HASTA;

CREATE VIEW V_REPORTE_ESTADO AS
SELECT ESTADO,
       CAST(CASE ESTADO WHEN 'borrador' THEN 1 WHEN 'pendiente' THEN 2
                        WHEN 'devuelta' THEN 3 WHEN 'visto_bueno' THEN 4
                        WHEN 'enviada' THEN 5 WHEN 'aprobada' THEN 6
                        WHEN 'rechazada' THEN 7 WHEN 'descartada' THEN 8
                        ELSE 9 END AS INTEGER) AS ORDEN,
       CAST(SUM(CANTIDAD) AS INTEGER) AS CANTIDAD,
       CAST(COALESCE(SUM(MONTO_TOTAL), 0) AS NUMERIC(18,2)) AS MONTO
  FROM V_REPORTE_DIA
 WHERE PERIODO = 'actual'
 GROUP BY ESTADO;

CREATE VIEW V_REPORTE_ASESOR AS
SELECT ASESOR_ID, ASESOR_NOMBRE,
       CAST(SUM(ENVIADAS) AS INTEGER) AS CANTIDAD,
       CAST(SUM(APROBADAS) AS INTEGER) AS APROBADAS,
       CAST(SUM(RECHAZADAS) AS INTEGER) AS RECHAZADAS,
       CAST(SUM(DESCARTADAS) AS INTEGER) AS DESCARTADAS,
       CAST(COALESCE(SUM(MONTO_APROBADO), 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO,
       CAST(COALESCE(SUM(MONTO_ENVIADO), 0) AS NUMERIC(18,2)) AS MONTO_TOTAL,
       CAST(COALESCE(SUM(APROBADAS) * 100.0000
            / NULLIF(SUM(APROBADAS) + SUM(RECHAZADAS), 0), 0)
            AS NUMERIC(5,2)) AS TASA_APROBACION
  FROM V_REPORTE_DIA
 WHERE PERIODO = 'actual' AND DEL_CLIENTE
 GROUP BY ASESOR_ID, ASESOR_NOMBRE;

CREATE VIEW V_REPORTE_TIPO AS
SELECT TIPO_TRABAJO_ID, TIPO_TRABAJO_NOMBRE,
       CAST(SUM(ENVIADAS) AS INTEGER) AS CANTIDAD,
       CAST(SUM(APROBADAS) AS INTEGER) AS APROBADAS,
       CAST(SUM(RECHAZADAS) AS INTEGER) AS RECHAZADAS,
       CAST(SUM(DESCARTADAS) AS INTEGER) AS DESCARTADAS,
       CAST(COALESCE(SUM(MONTO_APROBADO), 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO,
       CAST(COALESCE(SUM(MONTO_ENVIADO), 0) AS NUMERIC(18,2)) AS MONTO_TOTAL,
       CAST(COALESCE(SUM(APROBADAS) * 100.0000
            / NULLIF(SUM(APROBADAS) + SUM(RECHAZADAS), 0), 0)
            AS NUMERIC(5,2)) AS TASA_APROBACION
  FROM V_REPORTE_DIA
 WHERE PERIODO = 'actual' AND DEL_CLIENTE
 GROUP BY TIPO_TRABAJO_ID, TIPO_TRABAJO_NOMBRE;

CREATE VIEW V_REPORTE_MES AS
WITH RECURSIVE
P AS (
  SELECT DESDE, HASTA,
         CAST(EXTRACT(YEAR FROM DESDE) * 100 + EXTRACT(MONTH FROM DESDE)
           AS INTEGER) AS CLAVE_DESDE,
         CAST(EXTRACT(YEAR FROM HASTA) * 100 + EXTRACT(MONTH FROM HASTA)
           AS INTEGER) AS CLAVE_HASTA,
         CAST((EXTRACT(YEAR FROM HASTA) * 12 + EXTRACT(MONTH FROM HASTA))
            - (EXTRACT(YEAR FROM DESDE) * 12 + EXTRACT(MONTH FROM DESDE))
            AS INTEGER) AS SALTO
    FROM V_REPORTE_PERIODO
   WHERE PERIODO = 'actual'),
D AS (
  SELECT CAST(ANIO * 100 + MES AS INTEGER) AS CLAVE, ENVIADAS, APROBADAS,
         RECHAZADAS, DESCARTADAS, MONTO_APROBADO, MONTO_ENVIADO
    FROM V_REPORTE_DIA
   WHERE PERIODO = 'actual' AND DEL_CLIENTE),
L AS (
  SELECT CASE WHEN P.SALTO < 36 THEN P.CLAVE_DESDE
              ELSE (SELECT MIN(CLAVE) FROM D) END AS PRIMERA,
         CASE WHEN P.SALTO < 36 THEN P.CLAVE_HASTA
              ELSE (SELECT MAX(CLAVE) FROM D) END AS ULTIMA
    FROM P),
M (INICIO, ULTIMA) AS (
  SELECT CAST((PRIMERA / 100) || '-' || MOD(PRIMERA, 100) || '-01' AS DATE),
         ULTIMA
    FROM L
   WHERE PRIMERA IS NOT NULL
  UNION ALL
  SELECT DATEADD(1 MONTH TO INICIO), ULTIMA
    FROM M
   WHERE EXTRACT(YEAR FROM DATEADD(1 MONTH TO INICIO)) * 100
       + EXTRACT(MONTH FROM DATEADD(1 MONTH TO INICIO)) <= ULTIMA)
SELECT CAST(EXTRACT(YEAR FROM M.INICIO) AS INTEGER) AS ANIO,
       CAST(EXTRACT(MONTH FROM M.INICIO) AS INTEGER) AS MES,
       CAST(COALESCE(SUM(D.ENVIADAS), 0) AS INTEGER) AS CANTIDAD,
       CAST(COALESCE(SUM(D.APROBADAS), 0) AS INTEGER) AS APROBADAS,
       CAST(COALESCE(SUM(D.RECHAZADAS), 0) AS INTEGER) AS RECHAZADAS,
       CAST(COALESCE(SUM(D.DESCARTADAS), 0) AS INTEGER) AS DESCARTADAS,
       CAST(COALESCE(SUM(D.MONTO_APROBADO), 0) AS NUMERIC(18,2))
         AS MONTO_APROBADO,
       CAST(COALESCE(SUM(D.MONTO_ENVIADO), 0) AS NUMERIC(18,2)) AS MONTO_TOTAL,
       CAST(COALESCE(SUM(D.APROBADAS) * 100.0000
            / NULLIF(SUM(D.APROBADAS) + SUM(D.RECHAZADAS), 0), 0)
            AS NUMERIC(5,2)) AS TASA_APROBACION
  FROM M
  LEFT JOIN D ON D.CLAVE = EXTRACT(YEAR FROM M.INICIO) * 100
                         + EXTRACT(MONTH FROM M.INICIO)
 GROUP BY M.INICIO;

CREATE VIEW V_REPORTE_CLIENTE AS
SELECT CLIENTE_ID, CLIENTE_NOMBRE,
       CAST(COUNT(*) AS INTEGER) AS ENVIADAS,
       MAX(FECHA_ENVIO) AS ULTIMO_ENVIO,
       CAST(SUM(CASE WHEN ESTADO = 'aprobada' THEN 1 ELSE 0 END) AS INTEGER)
         AS APROBADAS,
       CAST(SUM(CASE WHEN ESTADO = 'rechazada' THEN 1 ELSE 0 END) AS INTEGER)
         AS RECHAZADAS,
       CAST(SUM(CASE WHEN SIN_RESPUESTA THEN 1 ELSE 0 END) AS INTEGER)
         AS SIN_RESPUESTA,
       CAST(COALESCE(SUM(CASE WHEN SIN_RESPUESTA THEN MONTO_TOTAL END), 0)
            AS NUMERIC(18,2)) AS MONTO_SIN_RESPUESTA,
       CAST(SUM(CASE WHEN ESTADO NOT IN ('aprobada', 'rechazada')
                      AND NOT SIN_RESPUESTA THEN 1 ELSE 0 END) AS INTEGER)
         AS EN_ESPERA,
       CAST(SUM(CASE WHEN SIN_RESPUESTA THEN 1 ELSE 0 END) * 100.0000
            / COUNT(*) AS NUMERIC(5,2)) AS PORCENTAJE_SIN_RESPUESTA
  FROM (SELECT R.CLIENTE_ID, R.CLIENTE_NOMBRE, R.ESTADO, R.FECHA_ENVIO,
               R.MONTO_TOTAL,
               (R.ESTADO = 'descartada'
                OR (R.ESTADO = 'enviada'
                    AND DATEADD(COALESCE(R.DIAS_SIN_RESPUESTA, 0) DAY
                        TO R.FECHA_ENVIO) < CURRENT_TIMESTAMP))
                 AS SIN_RESPUESTA
          FROM V_REPORTE_PERIODO P
          JOIN V_CLIENTES_RESPUESTA R
            ON R.FECHA_ENVIO >= P.DESDE
           AND R.FECHA_ENVIO < DATEADD(1 DAY TO P.HASTA)
           AND (P.USUARIO = 0 OR R.ASESOR_ID = P.USUARIO
                OR R.ELABORADA_POR = P.USUARIO)
         WHERE P.PERIODO = 'actual')
 GROUP BY CLIENTE_ID, CLIENTE_NOMBRE;

