/* ============================================================================
   Anovo - Migracion 43: condiciones de la cotizacion para escoger
   ----------------------------------------------------------------------------
   Forma de pago, plazo de entrega y garantia eran texto libre (migracion 34).
   Pasan a escogerse:

   - FORMAS_PAGO: catalogo con el mismo molde que TIPOS_MATERIAL (nombre,
     ACTIVO, fechas). Se inactiva, no se borra: ROL_BACKEND sin DELETE.
   - D_UNIDAD_PLAZO: unidad de tiempo para el plazo y la garantia. Codigos en
     ASCII; los textos con tildes los pone cada cliente.
   - EMPRESA (el valor por defecto) y COTIZACIONES (lo de cada una) reciben
     FORMA_PAGO_ID y cantidad + unidad para la garantia y el plazo. Cantidad
     y unidad van juntas o ninguna.
   - COTIZACIONES.FORMA_PAGO se queda: es la copia del nombre al escogerla,
     como el precio de las lineas. Si el catalogo cambia el nombre, la
     cotizacion enviada no cambia.
   - Salen las columnas de texto que quedan sin uso: EMPRESA.FORMA_PAGO,
     PLAZO_ENTREGA y GARANTIA, y COTIZACIONES.PLAZO_ENTREGA y GARANTIA.
     Se verifico antes que estaban vacias en todas las filas y que ninguna
     vista ni disparador dependia de ellas.

   Los nombres reales de las formas de pago se validan con Anovo; para probar
   se cargan con Db/datos-prueba/formas_pago_demo.sql.

   Todo en ASCII.
   ============================================================================ */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 43: condiciones para escoger') FROM RDB$DATABASE;

/* ----------------------------------------------------------------------------
   1. Catalogo de formas de pago
   ---------------------------------------------------------------------------- */
CREATE TABLE FORMAS_PAGO (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE             D_NOMBRE NOT NULL UNIQUE,
  ACTIVO             D_BOOLEANO,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP
);

CREATE DOMAIN D_UNIDAD_PLAZO AS VARCHAR(15)
  CHECK (VALUE IS NULL OR VALUE IN
    ('dias', 'dias_habiles', 'semanas', 'meses', 'anios'));

COMMIT;

SET TERM ^ ;

CREATE TRIGGER TR_FORMAS_PAGO_BI_DEF FOR FORMAS_PAGO ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ACTIVO IS NULL) THEN NEW.ACTIVO = TRUE;
  IF (NEW.FECHA_CREACION IS NULL) THEN NEW.FECHA_CREACION = CURRENT_TIMESTAMP;
  IF (NEW.FECHA_MODIFICACION IS NULL) THEN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TR_FORMAS_PAGO_BU FOR FORMAS_PAGO ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

SET TERM ; ^

GRANT SELECT, INSERT, UPDATE ON FORMAS_PAGO TO ROL_BACKEND;

/* ----------------------------------------------------------------------------
   2. Condiciones por defecto (EMPRESA) y de cada cotizacion
   ---------------------------------------------------------------------------- */
ALTER TABLE EMPRESA ADD FORMA_PAGO_ID INTEGER;
ALTER TABLE EMPRESA ADD PLAZO_ENTREGA_CANTIDAD SMALLINT;
ALTER TABLE EMPRESA ADD PLAZO_ENTREGA_UNIDAD D_UNIDAD_PLAZO;
ALTER TABLE EMPRESA ADD GARANTIA_CANTIDAD SMALLINT;
ALTER TABLE EMPRESA ADD GARANTIA_UNIDAD D_UNIDAD_PLAZO;

ALTER TABLE COTIZACIONES ADD FORMA_PAGO_ID INTEGER;
ALTER TABLE COTIZACIONES ADD PLAZO_ENTREGA_CANTIDAD SMALLINT;
ALTER TABLE COTIZACIONES ADD PLAZO_ENTREGA_UNIDAD D_UNIDAD_PLAZO;
ALTER TABLE COTIZACIONES ADD GARANTIA_CANTIDAD SMALLINT;
ALTER TABLE COTIZACIONES ADD GARANTIA_UNIDAD D_UNIDAD_PLAZO;

COMMIT;

ALTER TABLE EMPRESA ADD CONSTRAINT FK_EMPRESA_FORMA_PAGO
  FOREIGN KEY (FORMA_PAGO_ID) REFERENCES FORMAS_PAGO (ID);
ALTER TABLE EMPRESA ADD CONSTRAINT CK_EMPRESA_PLAZO_ENTREGA
  CHECK ((PLAZO_ENTREGA_CANTIDAD IS NULL AND PLAZO_ENTREGA_UNIDAD IS NULL) OR
         (PLAZO_ENTREGA_CANTIDAD > 0 AND PLAZO_ENTREGA_UNIDAD IS NOT NULL));
ALTER TABLE EMPRESA ADD CONSTRAINT CK_EMPRESA_GARANTIA
  CHECK ((GARANTIA_CANTIDAD IS NULL AND GARANTIA_UNIDAD IS NULL) OR
         (GARANTIA_CANTIDAD > 0 AND GARANTIA_UNIDAD IS NOT NULL));

ALTER TABLE COTIZACIONES ADD CONSTRAINT FK_COTIZACIONES_FORMA_PAGO
  FOREIGN KEY (FORMA_PAGO_ID) REFERENCES FORMAS_PAGO (ID);
ALTER TABLE COTIZACIONES ADD CONSTRAINT CK_COTIZ_PLAZO_ENTREGA
  CHECK ((PLAZO_ENTREGA_CANTIDAD IS NULL AND PLAZO_ENTREGA_UNIDAD IS NULL) OR
         (PLAZO_ENTREGA_CANTIDAD > 0 AND PLAZO_ENTREGA_UNIDAD IS NOT NULL));
ALTER TABLE COTIZACIONES ADD CONSTRAINT CK_COTIZ_GARANTIA
  CHECK ((GARANTIA_CANTIDAD IS NULL AND GARANTIA_UNIDAD IS NULL) OR
         (GARANTIA_CANTIDAD > 0 AND GARANTIA_UNIDAD IS NOT NULL));

/* ----------------------------------------------------------------------------
   3. Columnas de texto que quedan sin uso
   ---------------------------------------------------------------------------- */
ALTER TABLE EMPRESA DROP FORMA_PAGO;
ALTER TABLE EMPRESA DROP PLAZO_ENTREGA;
ALTER TABLE EMPRESA DROP GARANTIA;
ALTER TABLE COTIZACIONES DROP PLAZO_ENTREGA;
ALTER TABLE COTIZACIONES DROP GARANTIA;

COMMIT;

COMMENT ON TABLE FORMAS_PAGO IS
  'Formas de pago que se escogen en la cotizacion. Se inactivan, no se borran.';
COMMENT ON COLUMN EMPRESA.FORMA_PAGO_ID IS
  'Forma de pago por defecto; se copia a cada cotizacion nueva.';
COMMENT ON COLUMN EMPRESA.PLAZO_ENTREGA_CANTIDAD IS
  'Plazo de entrega por defecto (cantidad); se copia a cada cotizacion nueva.';
COMMENT ON COLUMN EMPRESA.GARANTIA_CANTIDAD IS
  'Garantia por defecto (cantidad); se copia a cada cotizacion nueva.';
COMMENT ON COLUMN COTIZACIONES.FORMA_PAGO IS
  'Copia del nombre de la forma de pago al escogerla; es lo que se imprime.';
COMMENT ON COLUMN COTIZACIONES.FORMA_PAGO_ID IS
  'Forma de pago escogida en la cotizacion.';

INSERT INTO ESQUEMA_MIGRACIONES (NUMERO, NOMBRE)
  VALUES (43, '43_condiciones_seleccionables');

COMMIT;

