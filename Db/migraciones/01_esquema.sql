/* ============================================================================
   Anovo - Sistema de Cotizaciones - Esquema Firebird 4.0  (base de ENTREGA)
   ----------------------------------------------------------------------------
   La base se crea aparte (ver LEEME.md); este script solo trae el DDL.
   Para reconstruir desde cero: borrar el .fdb y volver a crearlo. Firebird no
   tiene DROP IF EXISTS, asi que no se intenta limpiar.

   Orden:  01_esquema -> 02_auditoria -> 03_datos -> 04_usuario
   ============================================================================ */

/* ============================================================================
   DOMINIOS
   ============================================================================ */
CREATE DOMAIN D_MONTO       AS NUMERIC(15,2) DEFAULT 0 NOT NULL;
CREATE DOMAIN D_CANTIDAD    AS NUMERIC(12,3) DEFAULT 0 NOT NULL;
CREATE DOMAIN D_NOMBRE      AS VARCHAR(120);
CREATE DOMAIN D_DESCRIPCION AS VARCHAR(500);
CREATE DOMAIN D_ESTADO      AS VARCHAR(20);
CREATE DOMAIN D_UUID        AS VARCHAR(36);
CREATE DOMAIN D_BOOLEANO    AS BOOLEAN DEFAULT TRUE NOT NULL;
CREATE DOMAIN D_TIMESTAMP   AS TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL;
/* foVersion de DMVC. La mantiene el framework dentro del UPDATE, sin
   disparador: uno que la tocara pelearia con el. */
CREATE DOMAIN D_VERSION     AS INTEGER DEFAULT 0 NOT NULL;

/* ============================================================================
   1. AUDITORIA
   La escribe el disparador, no la aplicacion. El usuario del backend no tiene
   permiso aqui: ver 04_usuario.sql.
   ============================================================================ */
CREATE TABLE AUDITORIA (
  ID          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID  INTEGER,
  ACCION      VARCHAR(50)  NOT NULL,
  ENTIDAD     VARCHAR(50)  NOT NULL,
  ENTIDAD_ID  INTEGER,
  DETALLE     D_DESCRIPCION,
  FECHA       D_TIMESTAMP
);

CREATE INDEX IDX_AUDITORIA_FECHA   ON AUDITORIA (FECHA);
CREATE INDEX IDX_AUDITORIA_ENTIDAD ON AUDITORIA (ENTIDAD, ENTIDAD_ID);

/* ============================================================================
   2. USUARIOS Y ROLES
   ============================================================================ */
CREATE TABLE ROLES (
  ID     INTEGER PRIMARY KEY,
  CODIGO VARCHAR(20) NOT NULL UNIQUE,
  NOMBRE D_NOMBRE NOT NULL
);

CREATE TABLE USUARIOS (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CORREO             VARCHAR(150) NOT NULL UNIQUE,
  NOMBRE             D_NOMBRE NOT NULL,
  ROL_ID             INTEGER NOT NULL REFERENCES ROLES(ID),
  ACTIVO             D_BOOLEANO,
  DEBE_CAMBIAR_CLAVE D_BOOLEANO DEFAULT FALSE NOT NULL,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP
);

CREATE TABLE USUARIOS_CLAVES (
  ID           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID   INTEGER NOT NULL REFERENCES USUARIOS(ID),
  CLAVE_HASH   VARCHAR(255) NOT NULL,
  ACTIVO       D_BOOLEANO,
  FECHA_CAMBIO D_TIMESTAMP
);

CREATE INDEX IDX_CLAVES_USUARIO_ACTIVO ON USUARIOS_CLAVES (USUARIO_ID, ACTIVO);

CREATE TABLE EMPRESA (
  ID                  INTEGER PRIMARY KEY,
  RAZON_SOCIAL        D_NOMBRE NOT NULL,
  CEDULA_JURIDICA     VARCHAR(20) NOT NULL UNIQUE,
  DIRECCION           D_DESCRIPCION,
  TELEFONO_FIJO       VARCHAR(30),
  CELULAR             VARCHAR(30),
  CORREO              VARCHAR(150),
  REPRESENTANTE_LEGAL D_NOMBRE,
  CUENTA_BANCARIA     VARCHAR(60),
  MODIFICADO_POR      INTEGER REFERENCES USUARIOS(ID),
  FECHA_MODIFICACION  D_TIMESTAMP
);

/* ============================================================================
   3. CLIENTES
   Datos personales: aplica Ley 8968. No exponerlos por RQL abierto.
   ============================================================================ */
CREATE TABLE CLIENTES (
  ID                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL             D_UUID UNIQUE,
  NOMBRE                 D_NOMBRE NOT NULL,
  IDENTIFICACION         VARCHAR(30),
  TELEFONO               VARCHAR(30),
  CORREO                 VARCHAR(150),
  DIRECCION              D_DESCRIPCION,
  LATITUD                NUMERIC(9,6),
  LONGITUD               NUMERIC(9,6),
  ACTIVO                 D_BOOLEANO,
  EXONERADO              D_BOOLEANO DEFAULT FALSE NOT NULL,
  CODIGO_EXONERACION     VARCHAR(30),
  CONSENTIMIENTO_ESTADO  D_ESTADO DEFAULT 'pendiente' NOT NULL,
  CONSENTIMIENTO_FECHA   TIMESTAMP,
  CONSENTIMIENTO_VERSION VARCHAR(10),
  ANONIMIZADO            D_BOOLEANO DEFAULT FALSE NOT NULL,
  FECHA_CREACION         D_TIMESTAMP,
  FECHA_MODIFICACION     D_TIMESTAMP,
  OBJVERSION             D_VERSION,
  CONSTRAINT CK_CLIENTES_EXONERACION CHECK (EXONERADO = FALSE OR CODIGO_EXONERACION IS NOT NULL),
  CONSTRAINT CK_CLIENTES_CONS_ESTADO CHECK (CONSENTIMIENTO_ESTADO IN ('pendiente','firmado','revocado'))
);

CREATE TABLE CLIENTE_CONTACTOS (
  ID                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL             D_UUID UNIQUE,
  CLIENTE_ID             INTEGER NOT NULL REFERENCES CLIENTES(ID),
  NOMBRE                 D_NOMBRE NOT NULL,
  AREA                   VARCHAR(80),
  TELEFONO               VARCHAR(30),
  CORREO                 VARCHAR(150),
  PRINCIPAL              D_BOOLEANO DEFAULT FALSE NOT NULL,
  CONSENTIMIENTO_ESTADO  D_ESTADO DEFAULT 'pendiente' NOT NULL,
  CONSENTIMIENTO_FECHA   TIMESTAMP,
  CONSENTIMIENTO_VERSION VARCHAR(10),
  ANONIMIZADO            D_BOOLEANO DEFAULT FALSE NOT NULL,
  ACTIVO                 D_BOOLEANO,
  FECHA_CREACION         D_TIMESTAMP,
  OBJVERSION             D_VERSION,
  CONSTRAINT CK_CONTACTOS_CONS_ESTADO CHECK (CONSENTIMIENTO_ESTADO IN ('pendiente','firmado','revocado'))
);

CREATE INDEX IDX_CONTACTOS_CLIENTE ON CLIENTE_CONTACTOS (CLIENTE_ID);

/* Fuente de verdad del consentimiento, solo agrega filas. Aqui vive la
   evidencia de la firma; las columnas de CLIENTES son cache del estado. */
CREATE TABLE CLIENTE_CONSENTIMIENTO_HISTORIAL (
  ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CLIENTE_ID              INTEGER NOT NULL REFERENCES CLIENTES(ID),
  CLIENTE_CONTACTO_ID     INTEGER REFERENCES CLIENTE_CONTACTOS(ID),
  ACCION                  VARCHAR(20) NOT NULL,
  VERSION_TEXTO           VARCHAR(10) NOT NULL,
  FECHA                   D_TIMESTAMP,
  FIRMANTE_NOMBRE         D_NOMBRE,
  FIRMANTE_IDENTIFICACION VARCHAR(30),
  FIRMA_IMAGEN            BLOB SUB_TYPE BINARY,
  FIRMA_MIME              VARCHAR(40),
  ORIGEN                  VARCHAR(20),
  CONSTRAINT CK_CONSHIST_ACCION CHECK (ACCION IN ('otorgado','revocado'))
);

CREATE INDEX IDX_CONSHIST_CLIENTE ON CLIENTE_CONSENTIMIENTO_HISTORIAL (CLIENTE_ID);

/* ============================================================================
   4. SOLICITUDES  (suben desde el movil)
   ============================================================================ */
CREATE TABLE SOLICITUDES (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL         D_UUID NOT NULL UNIQUE,
  CLIENTE_ID         INTEGER NOT NULL REFERENCES CLIENTES(ID),
  ASESOR_ID          INTEGER NOT NULL REFERENCES USUARIOS(ID),
  DESCRIPCION        D_DESCRIPCION NOT NULL,
  OBSERVACIONES      D_DESCRIPCION,
  /* Distintas a proposito: entre una y otra pueden pasar horas si el asesor
     estuvo sin cobertura. Confundirlas falsea los reportes de tiempo. */
  FECHA_CAPTURA      TIMESTAMP NOT NULL,
  FECHA_RECEPCION    D_TIMESTAMP,
  ESTADO             D_ESTADO NOT NULL,
  FECHA_MODIFICACION D_TIMESTAMP,
  OBJVERSION         D_VERSION
);

CREATE INDEX IDX_SOLICITUDES_ASESOR  ON SOLICITUDES (ASESOR_ID);
CREATE INDEX IDX_SOLICITUDES_CLIENTE ON SOLICITUDES (CLIENTE_ID);

/* Croquis: el JSON de trazos va en CONTENIDO_JSON. La imagen es opcional para
   croquis y obligatoria de hecho para fotos. */
CREATE TABLE SOLICITUD_ADJUNTOS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOLICITUD_ID   INTEGER NOT NULL REFERENCES SOLICITUDES(ID),
  UUID_LOCAL     D_UUID NOT NULL UNIQUE,
  TIPO           VARCHAR(10) NOT NULL,
  NOMBRE_ARCHIVO D_NOMBRE,
  MIME           VARCHAR(40),
  TAMANO_BYTES   INTEGER,
  /* El BLOB vive fuera de la fila: un SELECT que no pida CONTENIDO no toca los
     bytes. Listar adjuntos es igual de rapido con 50 fotos que con 5. */
  CONTENIDO      BLOB SUB_TYPE BINARY,
  CONTENIDO_JSON BLOB SUB_TYPE TEXT,
  ACTIVO         D_BOOLEANO,
  FECHA_CREACION D_TIMESTAMP,
  OBJVERSION     D_VERSION,
  CONSTRAINT CK_ADJUNTO_TAMANO CHECK (TAMANO_BYTES <= 3145728),
  CONSTRAINT CK_ADJUNTO_TIPO   CHECK (TIPO IN ('croquis','foto'))
);

CREATE INDEX IDX_ADJUNTOS_SOLICITUD ON SOLICITUD_ADJUNTOS (SOLICITUD_ID);

/* Una fila por medicion. Reemplaza LARGO/ANCHO/ALTO fijos: una pieza puede
   llevar varias. ETIQUETA correlaciona con un punto del croquis, no es unica. */
CREATE TABLE SOLICITUD_MEDIDAS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  UUID_LOCAL     D_UUID UNIQUE,
  SOLICITUD_ID   INTEGER NOT NULL REFERENCES SOLICITUDES(ID),
  CROQUIS_ID     INTEGER REFERENCES SOLICITUD_ADJUNTOS(ID),
  ETIQUETA       VARCHAR(5),
  TIPO_MEDIDA    VARCHAR(30) NOT NULL,
  VALOR          D_CANTIDAD,
  UNIDAD_MEDIDA  VARCHAR(10) DEFAULT 'cm' NOT NULL,
  OBSERVACION    D_DESCRIPCION,
  ORDEN          SMALLINT DEFAULT 0 NOT NULL,
  FECHA_CREACION D_TIMESTAMP,
  OBJVERSION     D_VERSION
);

CREATE INDEX IDX_MEDIDAS_SOLICITUD ON SOLICITUD_MEDIDAS (SOLICITUD_ID);

/* ============================================================================
   5. CATALOGOS  (el precio va en tabla aparte, ACTIVO marca la fila vigente)
   ============================================================================ */
CREATE TABLE MATERIALES (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO             VARCHAR(30) NOT NULL UNIQUE,
  NOMBRE             D_NOMBRE NOT NULL,
  DESCRIPCION        D_DESCRIPCION,
  UNIDAD_MEDIDA      VARCHAR(20) NOT NULL,
  ACTIVO             D_BOOLEANO,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP
);

CREATE TABLE MATERIALES_PRECIOS (
  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MATERIAL_ID     INTEGER NOT NULL REFERENCES MATERIALES(ID),
  COSTO_UNITARIO  D_MONTO,
  PRECIO_UNITARIO D_MONTO,
  ACTIVO          D_BOOLEANO,
  FECHA_VIGENCIA  D_TIMESTAMP,
  MODIFICADO_POR  INTEGER REFERENCES USUARIOS(ID)
);

CREATE INDEX IDX_MATERIALES_PRECIO_ACTIVO ON MATERIALES_PRECIOS (MATERIAL_ID, ACTIVO);

CREATE TABLE MANO_OBRA_CATEGORIA (
  ID     INTEGER PRIMARY KEY,
  CODIGO VARCHAR(20) NOT NULL UNIQUE,
  NOMBRE D_NOMBRE NOT NULL
);

CREATE TABLE MANO_OBRA (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO             VARCHAR(30) NOT NULL UNIQUE,
  CATEGORIA_ID       INTEGER NOT NULL REFERENCES MANO_OBRA_CATEGORIA(ID),
  DESCRIPCION        D_DESCRIPCION NOT NULL,
  UNIDAD_MEDIDA      VARCHAR(20) NOT NULL,
  ACTIVO             D_BOOLEANO,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP
);

CREATE INDEX IDX_MANO_OBRA_CATEGORIA ON MANO_OBRA (CATEGORIA_ID);

CREATE TABLE MANO_OBRA_PRECIOS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MANO_OBRA_ID   INTEGER NOT NULL REFERENCES MANO_OBRA(ID),
  COSTO_UNITARIO D_MONTO,
  ACTIVO         D_BOOLEANO,
  FECHA_VIGENCIA D_TIMESTAMP,
  MODIFICADO_POR INTEGER REFERENCES USUARIOS(ID)
);

CREATE INDEX IDX_MANO_OBRA_PRECIO_ACTIVO ON MANO_OBRA_PRECIOS (MANO_OBRA_ID, ACTIVO);

CREATE TABLE MAQUINAS (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODIGO             VARCHAR(30) NOT NULL UNIQUE,
  NOMBRE             D_NOMBRE NOT NULL,
  DESCRIPCION        D_DESCRIPCION,
  ACTIVO             D_BOOLEANO,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP
);

CREATE TABLE MAQUINAS_PRECIOS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  MAQUINA_ID     INTEGER NOT NULL REFERENCES MAQUINAS(ID),
  COSTO_HORA     D_MONTO,
  ACTIVO         D_BOOLEANO,
  FECHA_VIGENCIA D_TIMESTAMP,
  MODIFICADO_POR INTEGER REFERENCES USUARIOS(ID)
);

CREATE INDEX IDX_MAQUINAS_PRECIO_ACTIVO ON MAQUINAS_PRECIOS (MAQUINA_ID, ACTIVO);

/* ============================================================================
   6. COTIZACIONES
   ============================================================================ */
CREATE SEQUENCE GEN_COTIZACION_NUMERO;

CREATE TABLE TIPOS_TRABAJO (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE         D_NOMBRE NOT NULL UNIQUE,
  ACTIVO         D_BOOLEANO,
  FECHA_CREACION D_TIMESTAMP
);

CREATE TABLE COTIZACIONES (
  ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NUMERO              INTEGER NOT NULL UNIQUE,
  SOLICITUD_ID        INTEGER NOT NULL REFERENCES SOLICITUDES(ID),
  CLIENTE_ID          INTEGER NOT NULL REFERENCES CLIENTES(ID),
  TIPO_TRABAJO_ID     INTEGER REFERENCES TIPOS_TRABAJO(ID),
  DESCRIPCION_TRABAJO D_DESCRIPCION NOT NULL,
  ELABORADA_POR       INTEGER NOT NULL REFERENCES USUARIOS(ID),
  APROBADA_POR        INTEGER REFERENCES USUARIOS(ID),
  ESTADO              D_ESTADO NOT NULL,
  SUBTOTAL_MATERIALES D_MONTO,
  SUBTOTAL_MANO_OBRA  D_MONTO,
  SUBTOTAL_MAQUINA    D_MONTO,
  COSTO_TOTAL         D_MONTO,
  PORCENTAJE_AJUSTE   NUMERIC(5,2) DEFAULT 0 NOT NULL,
  MOTIVO_AJUSTE       D_DESCRIPCION,
  PORCENTAJE_IVA      NUMERIC(5,2) DEFAULT 0 NOT NULL,
  MONTO_IMPUESTO      D_MONTO,
  MONTO_TOTAL         D_MONTO,
  MOTIVO_RECHAZO      D_DESCRIPCION,
  FECHA_ELABORACION   D_TIMESTAMP,
  FECHA_APROBACION    TIMESTAMP,
  FECHA_ENVIO         TIMESTAMP,
  FECHA_MODIFICACION  D_TIMESTAMP,
  OBJVERSION          D_VERSION,
  CONSTRAINT CK_COTIZ_MOTIVO_AJUSTE  CHECK (PORCENTAJE_AJUSTE = 0 OR MOTIVO_AJUSTE IS NOT NULL),
  CONSTRAINT CK_COTIZ_MOTIVO_RECHAZO CHECK (ESTADO <> 'rechazada' OR MOTIVO_RECHAZO IS NOT NULL)
);

CREATE INDEX IDX_COTIZ_ESTADO ON COTIZACIONES (ESTADO);
CREATE INDEX IDX_COTIZ_FECHA  ON COTIZACIONES (FECHA_ELABORACION);

CREATE TABLE COTIZACION_DETALLE (
  ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COTIZACION_ID   INTEGER NOT NULL REFERENCES COTIZACIONES(ID) ON DELETE CASCADE,
  TIPO            VARCHAR(10) NOT NULL,
  MATERIAL_ID     INTEGER REFERENCES MATERIALES(ID),
  MANO_OBRA_ID    INTEGER REFERENCES MANO_OBRA(ID),
  MAQUINA_ID      INTEGER REFERENCES MAQUINAS(ID),
  DESCRIPCION     D_DESCRIPCION NOT NULL,
  UNIDAD_MEDIDA   VARCHAR(20),
  CANTIDAD        D_CANTIDAD,
  PRECIO_UNITARIO D_MONTO,
  SUBTOTAL        D_MONTO,
  ORDEN           SMALLINT DEFAULT 0 NOT NULL,
  CONSTRAINT CK_DETALLE_TIPO CHECK (
    (TIPO = 'material'  AND MATERIAL_ID  IS NOT NULL AND MANO_OBRA_ID IS NULL AND MAQUINA_ID IS NULL) OR
    (TIPO = 'mano_obra' AND MANO_OBRA_ID IS NOT NULL AND MATERIAL_ID  IS NULL AND MAQUINA_ID IS NULL) OR
    (TIPO = 'maquina'   AND MAQUINA_ID   IS NOT NULL AND MATERIAL_ID  IS NULL AND MANO_OBRA_ID IS NULL) OR
    (TIPO = 'nota'      AND MATERIAL_ID  IS NULL AND MANO_OBRA_ID IS NULL AND MAQUINA_ID IS NULL)
  )
);

CREATE INDEX IDX_DETALLE_COTIZ ON COTIZACION_DETALLE (COTIZACION_ID);

/* ============================================================================
   7. INDICES para la descarga incremental del movil
   ============================================================================ */
CREATE INDEX IDX_CLIENTES_MOD  ON CLIENTES   (FECHA_MODIFICACION);
CREATE INDEX IDX_MAT_MOD       ON MATERIALES (FECHA_MODIFICACION);
CREATE INDEX IDX_MANO_OBRA_MOD ON MANO_OBRA  (FECHA_MODIFICACION);
CREATE INDEX IDX_MAQUINAS_MOD  ON MAQUINAS   (FECHA_MODIFICACION);

/* ============================================================================
   8. DISPARADORES de FECHA_MODIFICACION
   BEFORE UPDATE: se asigna sobre NEW, sin segundo UPDATE y sin recursion.
   En SQL Server esto necesitaba guarda anti-recursion; aqui no.
   ============================================================================ */
SET TERM ^ ;

CREATE TRIGGER TR_USUARIOS_BU FOR USUARIOS ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_CLIENTES_BU FOR CLIENTES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_SOLICITUDES_BU FOR SOLICITUDES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_MATERIALES_BU FOR MATERIALES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_MANO_OBRA_BU FOR MANO_OBRA ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_MAQUINAS_BU FOR MAQUINAS ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_EMPRESA_BU FOR EMPRESA ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_COTIZACIONES_BU FOR COTIZACIONES ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

SET TERM ; ^

COMMIT;
