/* Anovo - Migracion 35: registro de cada cotizacion enviada por correo desde
   el servidor (minuta 14/2026, tema 2). Una fila por envio exitoso: a quien,
   con que asunto, por que cuenta y con que modo de autenticacion (contrasena
   de aplicacion u OAuth2). El PDF no se guarda: se regenera del documento.
   Solo insert. Todo en ASCII. */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 35: envios de cotizacion por correo') FROM RDB$DATABASE;

CREATE TABLE COTIZACION_ENVIOS (
  ID            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COTIZACION_ID INTEGER NOT NULL REFERENCES COTIZACIONES(ID) ON DELETE CASCADE,
  FECHA         D_TIMESTAMP,
  USUARIO_ID    INTEGER NOT NULL REFERENCES USUARIOS(ID),
  PARA          VARCHAR(300) NOT NULL,
  CC            VARCHAR(300),
  ASUNTO        VARCHAR(200) NOT NULL,
  REMITENTE     VARCHAR(150) NOT NULL,
  MODO          VARCHAR(10) NOT NULL,
  CONSTRAINT CK_COTIZ_ENVIOS_MODO CHECK (MODO IN ('clave', 'oauth2'))
);

CREATE INDEX IDX_COTIZ_ENVIOS_COTIZACION ON COTIZACION_ENVIOS (COTIZACION_ID);

COMMENT ON TABLE COTIZACION_ENVIOS IS
  'Cotizaciones enviadas al cliente por correo desde el servidor. Solo insert.';

COMMIT;

SET TERM ^ ;

CREATE TRIGGER TR_COTIZACION_ENVIOS_BI_DEF FOR COTIZACION_ENVIOS
ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.FECHA IS NULL) THEN NEW.FECHA = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TR_COTIZACION_ENVIOS_AUD FOR COTIZACION_ENVIOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_DETALLE VARCHAR(500);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  V_DETALLE = RDB$GET_CONTEXT('USER_SESSION', 'DETALLE');
  IF (INSERTING) THEN BEGIN V_ACCION = 'insertar'; V_ID = NEW.COTIZACION_ID; END
  ELSE IF (UPDATING) THEN BEGIN V_ACCION = 'actualizar'; V_ID = NEW.COTIZACION_ID; END
  ELSE BEGIN V_ACCION = 'borrar'; V_ID = OLD.COTIZACION_ID; END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'COTIZACION_ENVIOS', :V_ID, :V_DETALLE);
END^

SET TERM ; ^

GRANT SELECT, INSERT ON COTIZACION_ENVIOS TO ROL_BACKEND;
GRANT INSERT ON AUDITORIA TO TRIGGER TR_COTIZACION_ENVIOS_AUD;
GRANT USAGE ON EXCEPTION E_AUDITORIA_SIN_USUARIO TO TRIGGER TR_COTIZACION_ENVIOS_AUD;

INSERT INTO ESQUEMA_MIGRACIONES (NUMERO, NOMBRE)
  VALUES (35, '35_envios_cotizacion');

SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE', NULL) FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID', NULL) FROM RDB$DATABASE;

COMMIT;
