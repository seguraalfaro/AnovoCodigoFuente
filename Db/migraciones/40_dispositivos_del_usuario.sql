/* ============================================================================
   Anovo - Migracion 40: dispositivos del usuario (llave para renovar la sesion)
   ----------------------------------------------------------------------------
   El token del backend dura una hora y el movil sincroniza en segundo plano,
   muchas veces sin red al momento de capturar. Para que la subida no le pida
   la clave al asesor cada vez, cada telefono se registra al iniciar sesion y
   recibe una llave de dispositivo con la que pide un token nuevo.

   - USUARIOS_DISPOSITIVOS: una fila por telefono y usuario. Guarda solo el
     hash SHA-256 de la llave (64 hex), nunca la llave. El telefono la guarda
     cifrada con el Keystore de Android.
   - Rotacion: cada renovacion cambia la llave. La anterior queda en
     LLAVE_ANTERIOR_HASH; si alguien la vuelve a presentar, la llave fue
     copiada y el backend inactiva el dispositivo (MOTIVO = 'reuso').
   - FECHA_VENCE la fija el backend (tope sin uso); el disparador no decide
     nada, solo pone fechas y valores por defecto (regla de la 28).
   - Nada se borra: un dispositivo se inactiva con ACTIVO y MOTIVO
     ('cierre', 'reuso', 'clave', 'usuario', 'admin', 'reemplazo', 'vencido').
     El backend no tiene DELETE.
   - Auditoria: solo el registro y la inactivacion, no cada renovacion (una
     por hora por telefono llenaria AUDITORIA sin aportar nada).
   - V_USUARIOS_DISPOSITIVOS: lo que ve la oficina, sin los hashes.

   No rompe el contrato: el login y la renovacion nuevos se agregan aparte.

   Todo en ASCII.
   ============================================================================ */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 40: dispositivos del usuario') FROM RDB$DATABASE;

/* ----------------------------------------------------------------------------
   1. Tabla
   ---------------------------------------------------------------------------- */
CREATE TABLE USUARIOS_DISPOSITIVOS (
  ID                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  USUARIO_ID          INTEGER NOT NULL,
  UUID_DISPOSITIVO    D_UUID NOT NULL,
  NOMBRE              D_NOMBRE,
  LLAVE_HASH          CHAR(64) NOT NULL,
  LLAVE_ANTERIOR_HASH CHAR(64),
  FECHA_VENCE         TIMESTAMP NOT NULL,
  FECHA_ULTIMO_USO    TIMESTAMP,
  MOTIVO              D_ESTADO,
  ACTIVO              D_BOOLEANO,
  FECHA_CREACION      D_TIMESTAMP,
  FECHA_MODIFICACION  D_TIMESTAMP,
  OBJVERSION          D_VERSION,
  CONSTRAINT FK_DISPOSITIVOS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
  CONSTRAINT UQ_DISPOSITIVOS_LLAVE UNIQUE (LLAVE_HASH),
  CONSTRAINT CK_DISPOSITIVOS_MOTIVO CHECK (MOTIVO IS NULL OR MOTIVO IN
    ('cierre', 'reuso', 'clave', 'usuario', 'admin', 'reemplazo', 'vencido'))
);

CREATE INDEX IDX_DISPOSITIVOS_UUID     ON USUARIOS_DISPOSITIVOS (UUID_DISPOSITIVO, ACTIVO);
CREATE INDEX IDX_DISPOSITIVOS_USUARIO  ON USUARIOS_DISPOSITIVOS (USUARIO_ID, ACTIVO);
CREATE INDEX IDX_DISPOSITIVOS_ANTERIOR ON USUARIOS_DISPOSITIVOS (LLAVE_ANTERIOR_HASH);

COMMIT;

/* ----------------------------------------------------------------------------
   2. Vista de lectura (sin hashes)
   ---------------------------------------------------------------------------- */
CREATE VIEW V_USUARIOS_DISPOSITIVOS AS
SELECT D.ID, D.USUARIO_ID, U.CORREO, U.NOMBRE AS USUARIO_NOMBRE,
       D.UUID_DISPOSITIVO, D.NOMBRE, D.FECHA_VENCE, D.FECHA_ULTIMO_USO,
       D.MOTIVO, D.ACTIVO, D.FECHA_CREACION, D.FECHA_MODIFICACION
  FROM USUARIOS_DISPOSITIVOS D
  JOIN USUARIOS U ON U.ID = D.USUARIO_ID;

/* ----------------------------------------------------------------------------
   3. Disparadores (solo fechas, valores por defecto y auditoria)
   ---------------------------------------------------------------------------- */
SET TERM ^ ;

CREATE TRIGGER TR_USUARIOS_DISPOSITIVOS_BI_DEF FOR USUARIOS_DISPOSITIVOS
ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ACTIVO IS NULL) THEN NEW.ACTIVO = TRUE;
  IF (NEW.FECHA_CREACION IS NULL) THEN NEW.FECHA_CREACION = CURRENT_TIMESTAMP;
  IF (NEW.FECHA_MODIFICACION IS NULL) THEN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP;
  IF (NEW.OBJVERSION IS NULL) THEN NEW.OBJVERSION = 0;
END^

CREATE TRIGGER TR_USUARIOS_DISPOSITIVOS_BU FOR USUARIOS_DISPOSITIVOS
ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

/* Se audita el registro y la inactivacion; nunca los hashes. */
CREATE TRIGGER TR_USUARIOS_DISPOSITIVOS_AUD FOR USUARIOS_DISPOSITIVOS
ACTIVE AFTER INSERT OR UPDATE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
BEGIN
  IF (UPDATING AND OLD.ACTIVO IS NOT DISTINCT FROM NEW.ACTIVO) THEN EXIT;
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  IF (INSERTING) THEN
    INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
    VALUES (:V_USUARIO, 'insertar', 'USUARIOS_DISPOSITIVOS', NEW.ID,
            'registro del dispositivo ' || COALESCE(NEW.NOMBRE, NEW.UUID_DISPOSITIVO));
  ELSE
    INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
    VALUES (:V_USUARIO, IIF(NEW.ACTIVO, 'reactivar', 'inactivar'), 'USUARIOS_DISPOSITIVOS', NEW.ID,
            'motivo: ' || COALESCE(NEW.MOTIVO, '-'));
END^

SET TERM ; ^

/* ----------------------------------------------------------------------------
   4. Permisos del backend (sin DELETE)
   ---------------------------------------------------------------------------- */
GRANT SELECT, INSERT, UPDATE ON USUARIOS_DISPOSITIVOS TO ROL_BACKEND;
GRANT SELECT ON V_USUARIOS_DISPOSITIVOS TO ROL_BACKEND;

INSERT INTO ESQUEMA_MIGRACIONES (NUMERO, NOMBRE)
  VALUES (40, '40_dispositivos_del_usuario');

SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE', NULL) FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID', NULL) FROM RDB$DATABASE;
COMMIT;

