/* --- COTIZACIONES ---------------------------------------------------------
   Guarda el estado en DETALLE: la aprobacion es la accion mas sensible del
   sistema y saber a que estado paso vale mas que saber que cambio algo. */
CREATE TRIGGER TR_COTIZACIONES_AUD FOR COTIZACIONES
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_DET     VARCHAR(500);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  IF (INSERTING) THEN
  BEGIN
    V_ACCION = 'insertar';
    V_ID = NEW.ID;
    V_DET = 'estado ' || NEW.ESTADO;
  END
  ELSE IF (UPDATING) THEN
  BEGIN
    V_ACCION = 'actualizar';
    V_ID = NEW.ID;
    V_DET = 'estado ' || OLD.ESTADO || ' -> ' || NEW.ESTADO;
  END
  ELSE
  BEGIN
    V_ACCION = 'borrar';
    V_ID = OLD.ID;
    V_DET = 'estado ' || OLD.ESTADO;
  END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'COTIZACIONES', :V_ID, :V_DET);
END^

