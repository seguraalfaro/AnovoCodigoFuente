/* Anovo - Migracion 32: flujo real de la cotizacion e historial de estados.
   borrador -> pendiente (enviada a revision) -> devuelta (con observacion,
   vuelve a pendiente) -> visto_bueno -> enviada (al cliente) -> aprobada o
   rechazada (respuesta del cliente). Lo que hoy es 'aprobada' era el visto
   bueno interno: pasa a 'visto_bueno'. Las 'rechazada' se quedan como estan.
   COTIZACION_ESTADOS guarda cada paso con su fecha; ACTIVO marca el vigente.
   Lo llena un disparador al insertar o al cambiar ESTADO. Todo en ASCII. */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 32: flujo real de la cotizacion') FROM RDB$DATABASE;

CREATE TABLE COTIZACION_ESTADOS (
  ID            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  COTIZACION_ID INTEGER NOT NULL REFERENCES COTIZACIONES(ID) ON DELETE CASCADE,
  ESTADO        D_ESTADO NOT NULL,
  FECHA         D_TIMESTAMP,
  USUARIO_ID    INTEGER REFERENCES USUARIOS(ID),
  MOTIVO        D_DESCRIPCION,
  ACTIVO        D_BOOLEANO,
  CONSTRAINT CK_COTIZ_ESTADOS_ESTADO CHECK (ESTADO IN ('borrador', 'pendiente',
    'devuelta', 'visto_bueno', 'enviada', 'aprobada', 'rechazada'))
);

CREATE INDEX IDX_COTIZ_ESTADOS_ACTIVO ON COTIZACION_ESTADOS (COTIZACION_ID, ACTIVO);
CREATE INDEX IDX_COTIZ_ESTADOS_FECHA ON COTIZACION_ESTADOS (ESTADO, FECHA);

COMMENT ON TABLE COTIZACION_ESTADOS IS
  'Historial de estados de cada cotizacion. Una fila por paso; ACTIVO = TRUE solo en el vigente.';

COMMIT;

ALTER TABLE COTIZACIONES DROP CONSTRAINT CK_COTIZ_MOTIVO_RECHAZO;

COMMIT;

UPDATE COTIZACIONES SET ESTADO = 'visto_bueno' WHERE ESTADO = 'aprobada';
UPDATE COTIZACIONES SET ESTADO = 'devuelta'
 WHERE ESTADO = 'borrador' AND MOTIVO_RECHAZO IS NOT NULL;

COMMIT;

ALTER TABLE COTIZACIONES ADD CONSTRAINT CK_COTIZ_ESTADO CHECK (ESTADO IN
  ('borrador', 'pendiente', 'devuelta', 'visto_bueno', 'enviada', 'aprobada',
   'rechazada'));
ALTER TABLE COTIZACIONES ADD CONSTRAINT CK_COTIZ_MOTIVO_DEVUELTA CHECK
  (ESTADO <> 'devuelta' OR MOTIVO_RECHAZO IS NOT NULL);

COMMIT;

