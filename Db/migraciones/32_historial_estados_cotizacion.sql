  SELECT ID, 'enviada', FECHA_ENVIO, NULL, FALSE FROM COTIZACIONES
   WHERE FECHA_ENVIO IS NOT NULL;
INSERT INTO COTIZACION_ESTADOS (COTIZACION_ID, ESTADO, FECHA, USUARIO_ID, MOTIVO, ACTIVO)
  SELECT ID, ESTADO, FECHA_MODIFICACION, NULL, MOTIVO_RECHAZO, FALSE FROM COTIZACIONES
   WHERE ESTADO IN ('pendiente', 'devuelta', 'rechazada', 'aprobada');

UPDATE COTIZACION_ESTADOS E SET ACTIVO = TRUE
 WHERE E.ID = (SELECT MAX(X.ID) FROM COTIZACION_ESTADOS X
                 JOIN COTIZACIONES K ON K.ID = X.COTIZACION_ID
                WHERE X.COTIZACION_ID = E.COTIZACION_ID AND X.ESTADO = K.ESTADO);

COMMIT;

