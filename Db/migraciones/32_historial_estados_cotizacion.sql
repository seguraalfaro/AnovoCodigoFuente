/* Vistas con el flujo real. Cada evento cuenta en el dia en que ocurrio, segun
   COTIZACION_ESTADOS. DIAS_RESPUESTA va de la recepcion de la solicitud al
   envio al cliente; DIAS_EN_ESTADO, desde la fecha del estado vigente. */
ALTER VIEW V_COTIZACIONES AS
SELECT K.ID, K.NUMERO, K.ESTADO, K.DESCRIPCION_TRABAJO,
       K.SUBTOTAL_MATERIALES, K.SUBTOTAL_MANO_OBRA, K.SUBTOTAL_MAQUINA,
       K.COSTO_TOTAL, K.PORCENTAJE_AJUSTE, K.MOTIVO_AJUSTE, K.PORCENTAJE_IVA,
       K.MONTO_IMPUESTO, K.MONTO_TOTAL, K.MOTIVO_RECHAZO,
       K.FECHA_ELABORACION, K.FECHA_APROBACION, K.FECHA_ENVIO,
       K.FECHA_MODIFICACION,
       K.SOLICITUD_ID,
       COALESCE(S.FECHA_RECEPCION, S.FECHA_CAPTURA) AS FECHA_RECEPCION,
       K.CLIENTE_ID, C.NOMBRE AS CLIENTE_NOMBRE,
       S.ASESOR_ID, A.NOMBRE AS ASESOR_NOMBRE,
       K.ELABORADA_POR, E.NOMBRE AS ELABORADA_POR_NOMBRE,
       K.APROBADA_POR, P.NOMBRE AS APROBADA_POR_NOMBRE,
       K.TIPO_TRABAJO_ID, T.NOMBRE AS TIPO_TRABAJO_NOMBRE,
       CASE WHEN K.ESTADO = 'devuelta' THEN TRUE ELSE FALSE END AS DEVUELTA,
       CAST(DATEDIFF(DAY FROM COALESCE(
              (SELECT MAX(H.FECHA) FROM COTIZACION_ESTADOS H
                WHERE H.COTIZACION_ID = K.ID AND H.ACTIVO),
              K.FECHA_MODIFICACION) TO CURRENT_TIMESTAMP) AS INTEGER)
            AS DIAS_EN_ESTADO,
       CASE WHEN K.FECHA_ENVIO IS NOT NULL
            THEN CAST(DATEDIFF(DAY FROM COALESCE(S.FECHA_RECEPCION,
                      S.FECHA_CAPTURA) TO K.FECHA_ENVIO) AS INTEGER)
       END AS DIAS_RESPUESTA
  FROM COTIZACIONES K
  JOIN SOLICITUDES S ON S.ID = K.SOLICITUD_ID
  JOIN CLIENTES C ON C.ID = K.CLIENTE_ID
  JOIN USUARIOS A ON A.ID = S.ASESOR_ID
  JOIN USUARIOS E ON E.ID = K.ELABORADA_POR
  LEFT JOIN USUARIOS P ON P.ID = K.APROBADA_POR
  LEFT JOIN TIPOS_TRABAJO T ON T.ID = K.TIPO_TRABAJO_ID;

COMMIT;

ALTER VIEW V_TRABAJO_USUARIO AS
SELECT U.ID AS USUARIO_ID,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM V_SOLICITUDES S
         WHERE S.ESTADO = 'recibida' AND S.TIENE_COTIZACION = FALSE)
         AS POR_COTIZAR,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACIONES C
         WHERE C.ELABORADA_POR = U.ID AND C.ESTADO IN ('borrador', 'devuelta'))
         AS MIS_BORRADORES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACIONES C
         WHERE C.ELABORADA_POR = U.ID AND C.ESTADO = 'pendiente')
         AS EN_APROBACION,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACIONES C
         WHERE C.ELABORADA_POR = U.ID AND C.ESTADO = 'visto_bueno')
         AS POR_ENVIAR,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACIONES C
         WHERE C.ESTADO = 'pendiente' AND C.ELABORADA_POR <> U.ID)
         AS POR_APROBAR,
       (SELECT CAST(COALESCE(MAX(C.DIAS_EN_ESTADO), 0) AS INTEGER)
          FROM V_COTIZACIONES C
         WHERE C.ESTADO = 'pendiente' AND C.ELABORADA_POR <> U.ID)
         AS DIAS_MAS_ANTIGUA,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM COTIZACIONES C
         WHERE C.ESTADO = 'pendiente' AND C.ELABORADA_POR <> U.ID)
         AS MONTO_POR_APROBAR
  FROM USUARIOS U;

ALTER VIEW V_RESUMEN_MES AS
SELECT P.MES_DESDE AS DESDE, P.MES_HASTA AS HASTA,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM COTIZACION_ESTADOS H JOIN COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'enviada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS COTIZADO_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACION_ESTADOS H
         WHERE H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS APROBADAS_MES,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM COTIZACION_ESTADOS H JOIN COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS MONTO_APROBADO_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM COTIZACION_ESTADOS H
         WHERE H.ESTADO = 'rechazada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS RECHAZADAS_MES,
       (SELECT CAST(COALESCE(AVG(C.DIAS_RESPUESTA), 0) AS INTEGER)
          FROM COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'enviada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS RESPUESTA_MEDIA,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM USUARIOS U
          JOIN ROLES R ON R.ID = U.ROL_ID
         WHERE R.CODIGO = 'asesor' AND U.ACTIVO)
         AS ASESORES_ACTIVOS
  FROM V_PERIODO_ACTUAL P;

ALTER VIEW V_ASESORES_MES AS
SELECT U.ID AS ASESOR_ID, U.NOMBRE AS ASESOR_NOMBRE, U.ACTIVO,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM SOLICITUDES S
         WHERE S.ASESOR_ID = U.ID
           AND S.FECHA_CAPTURA >= P.MES_DESDE
           AND S.FECHA_CAPTURA < P.MES_HASTA)
         AS SOLICITUDES_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM SOLICITUDES S
         WHERE S.ASESOR_ID = U.ID
           AND S.ESTADO IN ('recibida', 'en_cotizacion')
           AND NOT EXISTS (SELECT 1 FROM COTIZACIONES X
                            WHERE X.SOLICITUD_ID = S.ID
                              AND X.ESTADO IN ('enviada', 'aprobada', 'rechazada')))
         AS ESPERANDO_COTIZACION,
       (SELECT CAST(COUNT(*) AS INTEGER)
          FROM COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE C.ASESOR_ID = U.ID AND H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS APROBADAS_MES,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE C.ASESOR_ID = U.ID AND H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS MONTO_APROBADO_MES
  FROM USUARIOS U
  JOIN ROLES R ON R.ID = U.ROL_ID
  CROSS JOIN V_PERIODO_ACTUAL P
 WHERE R.CODIGO = 'asesor';

ALTER VIEW V_COTIZACIONES_POR_ESTADO AS
SELECT ESTADO,
       CASE ESTADO WHEN 'borrador' THEN 1 WHEN 'pendiente' THEN 2
                   WHEN 'devuelta' THEN 3 WHEN 'visto_bueno' THEN 4
                   WHEN 'enviada' THEN 5 WHEN 'aprobada' THEN 6 ELSE 7 END
         AS ORDEN,
       CAST(COUNT(*) AS INTEGER) AS CANTIDAD,
       CAST(COALESCE(SUM(MONTO_TOTAL), 0) AS NUMERIC(18,2)) AS MONTO
  FROM COTIZACIONES
 GROUP BY ESTADO;

ALTER VIEW V_SEGUIMIENTO_ASESOR AS
SELECT S.ID, S.ASESOR_ID, S.FECHA_CAPTURA, S.CLIENTE_NOMBRE, S.DESCRIPCION,
       COALESCE(K.ESTADO, S.ESTADO) AS ESTADO,
       K.ID AS COTIZACION_ID, K.MONTO_TOTAL AS MONTO_APROBADO
  FROM V_SOLICITUDES S
  LEFT JOIN COTIZACIONES K ON K.ID =
       (SELECT MAX(X.ID) FROM COTIZACIONES X WHERE X.SOLICITUD_ID = S.ID);

ALTER VIEW V_COTIZACIONES_DIA AS
SELECT CAST(H.FECHA AS DATE) AS FECHA,
       CAST(EXTRACT(YEAR FROM H.FECHA) AS INTEGER) AS ANIO,
       CAST(EXTRACT(MONTH FROM H.FECHA) AS INTEGER) AS MES,
       H.ESTADO, K.ASESOR_ID, K.ASESOR_NOMBRE, K.TIPO_TRABAJO_ID,
       K.TIPO_TRABAJO_NOMBRE, K.ELABORADA_POR,
       CAST(COUNT(*) AS INTEGER) AS CANTIDAD,
       CAST(COALESCE(SUM(K.MONTO_TOTAL), 0) AS NUMERIC(18,2)) AS MONTO_TOTAL,
       CAST(SUM(CASE WHEN H.ESTADO = 'aprobada' THEN 1 ELSE 0 END)
            AS INTEGER) AS APROBADAS,
       CAST(SUM(CASE WHEN H.ESTADO = 'rechazada' THEN 1 ELSE 0 END)
            AS INTEGER) AS RECHAZADAS,
       CAST(COALESCE(SUM(CASE WHEN H.ESTADO = 'aprobada'
            THEN K.MONTO_TOTAL ELSE 0 END), 0) AS NUMERIC(18,2))
            AS MONTO_APROBADO,
       CAST(COALESCE(SUM(CASE WHEN H.ESTADO = 'enviada'
            THEN DATEDIFF(DAY FROM K.FECHA_RECEPCION TO H.FECHA) END), 0)
            AS INTEGER) AS SUMA_DIAS_RESPUESTA,
       CAST(COUNT(CASE WHEN H.ESTADO = 'enviada' THEN 1 END) AS INTEGER)
            AS CON_RESPUESTA
  FROM COTIZACION_ESTADOS H
  JOIN V_COTIZACIONES K ON K.ID = H.COTIZACION_ID
 GROUP BY 1, 2, 3, 4, 5, 6, 7, 8, 9;

COMMIT;

