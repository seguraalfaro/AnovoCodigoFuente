CREATE TRIGGER TR_COTIZACIONES_ESTADOS FOR COTIZACIONES
ACTIVE AFTER INSERT OR UPDATE POSITION 5
AS
BEGIN
  IF (UPDATING AND NEW.ESTADO = OLD.ESTADO) THEN
    EXIT;
  UPDATE COTIZACION_ESTADOS SET ACTIVO = FALSE
   WHERE COTIZACION_ID = NEW.ID AND ACTIVO = TRUE;
  INSERT INTO COTIZACION_ESTADOS (COTIZACION_ID, ESTADO, FECHA, USUARIO_ID,
    MOTIVO, ACTIVO)
  VALUES (NEW.ID, NEW.ESTADO, CURRENT_TIMESTAMP,
    CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER),
    IIF(NEW.ESTADO = 'devuelta', NEW.MOTIVO_RECHAZO, NULL), TRUE);
END^

SET TERM ; ^

GRANT SELECT, INSERT, UPDATE ON COTIZACION_ESTADOS TO TRIGGER TR_COTIZACIONES_ESTADOS;
