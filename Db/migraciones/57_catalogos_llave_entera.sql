         AS MONTO_AJUSTE
  FROM VT_COTIZACIONES K
  JOIN V_COTIZACIONES V ON V.ID = K.ID;

CREATE VIEW V_COTIZACIONES_SIN_RESPUESTA (ID, NUMERO, SOLICITUD_ID, CLIENTE_ID, TIPO_TRABAJO_ID, DESCRIPCION_TRABAJO, ELABORADA_POR, APROBADA_POR, ESTADO, SUBTOTAL_MATERIALES, SUBTOTAL_MANO_OBRA, SUBTOTAL_MAQUINA, COSTO_TOTAL, PORCENTAJE_AJUSTE, MOTIVO_AJUSTE, PORCENTAJE_IVA, MONTO_IMPUESTO, MONTO_TOTAL, MOTIVO_RECHAZO, FECHA_ELABORACION, FECHA_APROBACION, FECHA_ENVIO, FECHA_MODIFICACION, OBJVERSION, FORMA_PAGO, FORMA_PAGO_ID, PLAZO_ENTREGA_CANTIDAD, PLAZO_ENTREGA_UNIDAD, GARANTIA_CANTIDAD, GARANTIA_UNIDAD, ORDEN_COMPRA, FECHA_RECEPCION, CLIENTE_NOMBRE, ASESOR_ID, ASESOR_NOMBRE, ELABORADA_POR_NOMBRE, APROBADA_POR_NOMBRE, TIPO_TRABAJO_NOMBRE, DEVUELTA, DIAS_EN_ESTADO, DIAS_RESPUESTA, MONTO_AJUSTE) AS
