CREATE VIEW V_REPORTE_TIPO (TIPO_TRABAJO_ID, TIPO_TRABAJO_NOMBRE, CANTIDAD, APROBADAS, RECHAZADAS, DESCARTADAS, MONTO_APROBADO, MONTO_TOTAL, TASA_APROBACION) AS
