/* ============================================================================
   Anovo - Migracion 57: catalogos con llave entera
   ----------------------------------------------------------------------------
   Los estados, tipos y codigos dejan de guardarse como texto en cada fila y
   pasan a una tabla catalogo con llave entera (19/10/2026). Cada catalogo
   tiene ID fijo, CODIGO, NOMBRE (el texto que se ve en pantalla), ORDEN y
   ACTIVO; la columna de la tabla pasa a *_ID con llave foranea.

   - Estado de la cotizacion: el codigo 'pendiente' pasa a 'en_revision' y el
     catalogo dice lo que dice la pantalla, «Enviada a revision».
   - 17 catalogos: estados de cotizacion, solicitud, consentimiento y precio
     programado; acciones y origenes del consentimiento; tipos de
     identificacion, medida, linea, adjunto y excepcion; unidades de plazo;
     motivos de cierre de llave; modos de envio; magnitudes; modulos; ambitos.
   - Datos repetidos: COTIZACIONES pierde CLIENTE_ID (sale de la solicitud) y
     FORMA_PAGO en texto (sale de FORMAS_PAGO).
   - SOLICITUD_MEDIDAS y MAQUINAS apuntan a UNIDADES_MEDIDA; se agregan
     centimetro, milimetro y grado, que el croquis del movil ya usaba.
   - PRECIOS_PROGRAMADOS.PRECIO_ID, que apuntaba a tres tablas, se parte en
     tres columnas con llave foranea. AUDITORIA.USUARIO_ID gana llave foranea.
   - Vistas VT_<TABLA>: la tabla con sus codigos resueltos. Las demas vistas
     leen de ahi y siguen entregando el codigo de texto con el mismo nombre de
     columna, asi el contrato de la API no cambia.

   AUDITORIA.ACCION y ENTIDAD siguen en texto: la bitacora se lee sola.
   Los disparadores de fecha y de auditoria se apagan mientras se convierten
   los datos, para no mover FECHA_MODIFICACION ni llenar la bitacora con la
   conversion; el respaldo previo y ESQUEMA_MIGRACIONES dejan constancia.
   Correr con isql -ch UTF8.
   ============================================================================ */

