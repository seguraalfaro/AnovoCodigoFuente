  FROM USUARIOS U;

CREATE VIEW V_RESUMEN_MES (DESDE, HASTA, COTIZADO_MES, APROBADAS_MES, MONTO_APROBADO_MES, RECHAZADAS_MES, RESPUESTA_MEDIA, ASESORES_ACTIVOS, TASA_APROBACION) AS
SELECT R.*,
       CAST(COALESCE(R.APROBADAS_MES * 100.0000
            / NULLIF(R.APROBADAS_MES + R.RECHAZADAS_MES, 0), 0) AS NUMERIC(5,2))
         AS TASA_APROBACION
  FROM (SELECT P.MES_DESDE AS DESDE, P.MES_HASTA AS HASTA,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM VT_COTIZACION_ESTADOS H JOIN VT_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'enviada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS COTIZADO_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM VT_COTIZACION_ESTADOS H
         WHERE H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS APROBADAS_MES,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM VT_COTIZACION_ESTADOS H JOIN VT_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS MONTO_APROBADO_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM VT_COTIZACION_ESTADOS H
         WHERE H.ESTADO = 'rechazada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS RECHAZADAS_MES,
       (SELECT CAST(COALESCE(AVG(C.DIAS_RESPUESTA), 0) AS INTEGER)
          FROM VT_COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE H.ESTADO = 'enviada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS RESPUESTA_MEDIA,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM USUARIOS U
          JOIN ROLES R ON R.ID = U.ROL_ID
         WHERE R.CODIGO = 'asesor' AND U.ACTIVO)
         AS ASESORES_ACTIVOS
  FROM V_PERIODO_ACTUAL P) R;

CREATE VIEW V_ASESORES_MES (ASESOR_ID, ASESOR_NOMBRE, ACTIVO, SOLICITUDES_MES, ESPERANDO_COTIZACION, APROBADAS_MES, MONTO_APROBADO_MES) AS
SELECT U.ID AS ASESOR_ID, U.NOMBRE AS ASESOR_NOMBRE, U.ACTIVO,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM VT_SOLICITUDES S
         WHERE S.ASESOR_ID = U.ID
           AND S.FECHA_CAPTURA >= P.MES_DESDE
           AND S.FECHA_CAPTURA < P.MES_HASTA)
         AS SOLICITUDES_MES,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM VT_SOLICITUDES S
         WHERE S.ASESOR_ID = U.ID
           AND S.ESTADO IN ('recibida', 'en_cotizacion')
           AND NOT EXISTS (SELECT 1 FROM VT_COTIZACIONES X
                            WHERE X.SOLICITUD_ID = S.ID
                              AND X.ESTADO IN ('enviada', 'aprobada', 'rechazada')))
         AS ESPERANDO_COTIZACION,
       (SELECT CAST(COUNT(*) AS INTEGER)
          FROM VT_COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE C.ASESOR_ID = U.ID AND H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS APROBADAS_MES,
       (SELECT CAST(COALESCE(SUM(C.MONTO_TOTAL), 0) AS NUMERIC(18,2))
          FROM VT_COTIZACION_ESTADOS H JOIN V_COTIZACIONES C ON C.ID = H.COTIZACION_ID
         WHERE C.ASESOR_ID = U.ID AND H.ESTADO = 'aprobada'
           AND H.FECHA >= P.MES_DESDE AND H.FECHA < P.MES_HASTA)
         AS MONTO_APROBADO_MES
  FROM USUARIOS U
  JOIN ROLES R ON R.ID = U.ROL_ID
  CROSS JOIN V_PERIODO_ACTUAL P
 WHERE R.CODIGO = 'asesor';

CREATE VIEW V_COTIZACIONES_POR_ESTADO (ESTADO, ORDEN, CANTIDAD, MONTO) AS
