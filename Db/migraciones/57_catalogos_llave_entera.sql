       K.DESCRIPCION_TRABAJO, K.ELABORADA_POR, K.APROBADA_POR, K.ESTADO,
       K.SUBTOTAL_MATERIALES, K.SUBTOTAL_MANO_OBRA, K.SUBTOTAL_MAQUINA,
       K.COSTO_TOTAL, K.PORCENTAJE_AJUSTE, K.MOTIVO_AJUSTE, K.PORCENTAJE_IVA,
       K.MONTO_IMPUESTO, K.MONTO_TOTAL, K.MOTIVO_RECHAZO, K.FECHA_ELABORACION,
       K.FECHA_APROBACION, K.FECHA_ENVIO, K.FECHA_MODIFICACION, K.OBJVERSION,
