CREATE OR ALTER TRIGGER TR_COTIZACIONES_AUD FOR COTIZACIONES
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_DETALLE VARCHAR(500);
  DECLARE VARIABLE V_DET     VARCHAR(500);
  DECLARE VARIABLE V_ANTES   VARCHAR(20);
  DECLARE VARIABLE V_AHORA   VARCHAR(20);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  V_DETALLE = RDB$GET_CONTEXT('USER_SESSION', 'DETALLE');
  IF (NOT DELETING) THEN
    SELECT CODIGO FROM ESTADOS_COTIZACION WHERE ID = NEW.ESTADO_ID INTO :V_AHORA;
  IF (NOT INSERTING) THEN
    SELECT CODIGO FROM ESTADOS_COTIZACION WHERE ID = OLD.ESTADO_ID INTO :V_ANTES;
  IF (INSERTING) THEN
  BEGIN
    V_ACCION = 'insertar';
    V_ID = NEW.ID;
    V_DET = 'estado ' || V_AHORA;
  END
  ELSE IF (UPDATING) THEN
  BEGIN
    V_ACCION = 'actualizar';
    V_ID = NEW.ID;
    V_DET = 'estado ' || V_ANTES || ' -> ' || V_AHORA;
  END
  ELSE
  BEGIN
    V_ACCION = 'borrar';
    V_ID = OLD.ID;
    V_DET = 'estado ' || V_ANTES;
  END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'COTIZACIONES', :V_ID,
          COALESCE(:V_DETALLE, :V_DET));
END ^

CREATE OR ALTER TRIGGER TR_USUARIOS_DISPOSITIVOS_AUD FOR USUARIOS_DISPOSITIVOS
ACTIVE AFTER INSERT OR UPDATE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_MOTIVO  VARCHAR(20);
BEGIN
  IF (UPDATING AND OLD.ACTIVO IS NOT DISTINCT FROM NEW.ACTIVO) THEN EXIT;
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  IF (INSERTING) THEN
    INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
    VALUES (:V_USUARIO, 'insertar', 'USUARIOS_DISPOSITIVOS', NEW.ID,
            'registro del dispositivo ' || COALESCE(NEW.NOMBRE, NEW.UUID_DISPOSITIVO));
  ELSE
  BEGIN
    SELECT CODIGO FROM MOTIVOS_CIERRE WHERE ID = NEW.MOTIVO_CIERRE_ID
      INTO :V_MOTIVO;
    INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
    VALUES (:V_USUARIO, IIF(NEW.ACTIVO, 'reactivar', 'inactivar'), 'USUARIOS_DISPOSITIVOS', NEW.ID,
            'motivo: ' || COALESCE(:V_MOTIVO, '-'));
  END
END ^

