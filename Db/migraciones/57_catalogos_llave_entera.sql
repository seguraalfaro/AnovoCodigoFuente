              (SELECT MAX(H.FECHA) FROM VT_COTIZACION_ESTADOS H
                WHERE H.COTIZACION_ID = K.ID AND H.ACTIVO),
              K.FECHA_MODIFICACION) TO CURRENT_TIMESTAMP) AS INTEGER)
            AS DIAS_EN_ESTADO,
       CASE WHEN K.FECHA_ENVIO IS NOT NULL
            THEN CAST(DATEDIFF(DAY FROM COALESCE(S.FECHA_RECEPCION,
                      S.FECHA_CAPTURA) TO K.FECHA_ENVIO) AS INTEGER)
       END AS DIAS_RESPUESTA
  FROM VT_COTIZACIONES K
  JOIN VT_SOLICITUDES S ON S.ID = K.SOLICITUD_ID
  JOIN CLIENTES C ON C.ID = K.CLIENTE_ID
  JOIN USUARIOS A ON A.ID = S.ASESOR_ID
  JOIN USUARIOS E ON E.ID = K.ELABORADA_POR
  LEFT JOIN USUARIOS P ON P.ID = K.APROBADA_POR
  LEFT JOIN TIPOS_TRABAJO T ON T.ID = K.TIPO_TRABAJO_ID;

