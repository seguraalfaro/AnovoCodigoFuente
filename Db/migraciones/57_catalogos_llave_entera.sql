       T.UUID_LOCAL, T.NOMBRE_PROYECTO, K.NUMERO AS COTIZACION_NUMERO,
       MAXVALUE(T.FECHA_MODIFICACION,
                COALESCE(K.FECHA_MODIFICACION, T.FECHA_MODIFICACION))
         AS FECHA_CAMBIO
  FROM V_SOLICITUDES S
  JOIN VT_SOLICITUDES T ON T.ID = S.ID
  LEFT JOIN VT_COTIZACIONES K ON K.ID =
       (SELECT MAX(X.ID) FROM VT_COTIZACIONES X WHERE X.SOLICITUD_ID = S.ID);

CREATE VIEW V_COTIZACIONES_DIA (FECHA, ANIO, MES, ESTADO, ASESOR_ID, ASESOR_NOMBRE, TIPO_TRABAJO_ID, TIPO_TRABAJO_NOMBRE, ELABORADA_POR, CANTIDAD, MONTO_TOTAL, APROBADAS, RECHAZADAS, MONTO_APROBADO, SUMA_DIAS_RESPUESTA, CON_RESPUESTA) AS
SELECT CAST(H.FECHA AS DATE) AS FECHA,
       CAST(EXTRACT(YEAR FROM H.FECHA) AS INTEGER) AS ANIO,
       CAST(EXTRACT(MONTH FROM H.FECHA) AS INTEGER) AS MES,
       H.ESTADO, K.ASESOR_ID, K.ASESOR_NOMBRE, K.TIPO_TRABAJO_ID,
       K.TIPO_TRABAJO_NOMBRE, K.ELABORADA_POR,
       CAST(COUNT(*) AS INTEGER) AS CANTIDAD,
       CAST(COALESCE(SUM(K.MONTO_TOTAL), 0) AS NUMERIC(18,2)) AS MONTO_TOTAL,
       CAST(SUM(CASE WHEN H.ESTADO = 'aprobada' THEN 1 ELSE 0 END)
            AS INTEGER) AS APROBADAS,
       CAST(SUM(CASE WHEN H.ESTADO = 'rechazada' THEN 1 ELSE 0 END)
            AS INTEGER) AS RECHAZADAS,
       CAST(COALESCE(SUM(CASE WHEN H.ESTADO = 'aprobada'
            THEN K.MONTO_TOTAL ELSE 0 END), 0) AS NUMERIC(18,2))
            AS MONTO_APROBADO,
       CAST(COALESCE(SUM(CASE WHEN H.ESTADO = 'enviada'
            THEN DATEDIFF(DAY FROM K.FECHA_RECEPCION TO H.FECHA) END), 0)
            AS INTEGER) AS SUMA_DIAS_RESPUESTA,
       CAST(COUNT(CASE WHEN H.ESTADO = 'enviada' THEN 1 END) AS INTEGER)
            AS CON_RESPUESTA
  FROM VT_COTIZACION_ESTADOS H
  JOIN V_COTIZACIONES K ON K.ID = H.COTIZACION_ID
 GROUP BY 1, 2, 3, 4, 5, 6, 7, 8, 9;

