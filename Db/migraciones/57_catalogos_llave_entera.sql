CREATE VIEW VT_COTIZACIONES AS
SELECT K.*, E.CODIGO AS ESTADO, E.NOMBRE AS ESTADO_NOMBRE,
       S.CLIENTE_ID, F.NOMBRE AS FORMA_PAGO,
       UP.CODIGO AS PLAZO_ENTREGA_UNIDAD, UG.CODIGO AS GARANTIA_UNIDAD
  FROM COTIZACIONES K
  JOIN ESTADOS_COTIZACION E ON E.ID = K.ESTADO_ID
  JOIN SOLICITUDES S ON S.ID = K.SOLICITUD_ID
  LEFT JOIN FORMAS_PAGO F ON F.ID = K.FORMA_PAGO_ID
  LEFT JOIN UNIDADES_PLAZO UP ON UP.ID = K.PLAZO_ENTREGA_UNIDAD_ID
  LEFT JOIN UNIDADES_PLAZO UG ON UG.ID = K.GARANTIA_UNIDAD_ID;

