/* ============================================================================
   Anovo - Migracion 44: textos del consentimiento informado (Ley 8968)
   ----------------------------------------------------------------------------
   El texto que firma el cliente estaba fijo en el movil, que ademas no lo
   mostraba, y la version vivia en dos lugares que no coincidian ("v1" en el
   movil, "1.1" en el .env del servidor). Para la carga de la prueba
   (Rgto. art. 6) cada firma tiene que apuntar a un texto que se pueda volver a
   leer tal cual se firmo:

   - CONSENTIMIENTO_TEXTOS: una fila por version publicada. Una version no se
     edita: un cambio es una version nueva. VIGENTE marca la que se firma hoy
     (una sola; lo controla el servicio). VERSION es la misma columna que
     guarda CLIENTE_CONSENTIMIENTO_HISTORIAL.VERSION_TEXTO.
   - ROL_BACKEND con SELECT, INSERT y UPDATE (UPDATE solo para mover la marca
     VIGENTE); sin DELETE.
   - Disparador de auditoria: queda quien publico cada version y cuando cambio
     la vigente.

   Nace vacia: los textos llevan tildes y se cargan desde Configuracion. Para
   probar, Db/datos-prueba/consentimiento_demo.sql.

   Todo en ASCII.
   ============================================================================ */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 44: textos del consentimiento') FROM RDB$DATABASE;

CREATE TABLE CONSENTIMIENTO_TEXTOS (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  VERSION            VARCHAR(10) NOT NULL UNIQUE,
  TITULO             D_NOMBRE NOT NULL,
  CONTENIDO          VARCHAR(8000) NOT NULL,
  VIGENTE            BOOLEAN DEFAULT FALSE NOT NULL,
  VIGENTE_DESDE      TIMESTAMP,
  PUBLICADO_POR      INTEGER NOT NULL,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP,
  CONSTRAINT FK_CONSENT_TEXTOS_USUARIO FOREIGN KEY (PUBLICADO_POR)
    REFERENCES USUARIOS (ID)
);

COMMIT;

SET TERM ^ ;

CREATE TRIGGER TR_CONSENTIMIENTO_TEXTOS_BI_DEF FOR CONSENTIMIENTO_TEXTOS
ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.FECHA_CREACION IS NULL) THEN NEW.FECHA_CREACION = CURRENT_TIMESTAMP;
  IF (NEW.FECHA_MODIFICACION IS NULL) THEN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TR_CONSENTIMIENTO_TEXTOS_BU FOR CONSENTIMIENTO_TEXTOS
ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_CONSENTIMIENTO_TEXTOS_AUD FOR CONSENTIMIENTO_TEXTOS
ACTIVE AFTER INSERT OR UPDATE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
BEGIN
  IF (UPDATING AND OLD.VIGENTE IS NOT DISTINCT FROM NEW.VIGENTE) THEN EXIT;
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  IF (INSERTING) THEN
    INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
    VALUES (:V_USUARIO, 'insertar', 'CONSENTIMIENTO_TEXTOS', NEW.ID,
            'publicacion de la version ' || NEW.VERSION);
  ELSE
    INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
    VALUES (:V_USUARIO, 'actualizar', 'CONSENTIMIENTO_TEXTOS', NEW.ID,
            IIF(NEW.VIGENTE, 'pasa a vigente la version ', 'deja de regir la version ') || NEW.VERSION);
END^

SET TERM ; ^

GRANT SELECT, INSERT, UPDATE ON CONSENTIMIENTO_TEXTOS TO ROL_BACKEND;
GRANT INSERT ON AUDITORIA TO TRIGGER TR_CONSENTIMIENTO_TEXTOS_AUD;
GRANT USAGE ON EXCEPTION E_AUDITORIA_SIN_USUARIO TO TRIGGER TR_CONSENTIMIENTO_TEXTOS_AUD;

COMMENT ON TABLE CONSENTIMIENTO_TEXTOS IS
  'Versiones del texto del consentimiento informado (Ley 8968). No se editan ni se borran.';
COMMENT ON COLUMN CONSENTIMIENTO_TEXTOS.VIGENTE IS
  'La version que se firma hoy. Una sola; lo controla el servicio.';

INSERT INTO ESQUEMA_MIGRACIONES (NUMERO, NOMBRE)
  VALUES (44, '44_textos_del_consentimiento');

COMMIT;

