/* ============================================================================
   Anovo - Migracion 37: piezas de la solicitud
   ----------------------------------------------------------------------------
   En la revision del flujo de la nueva solicitud se encontro que el modelo no
   tenia piezas: las medidas y los adjuntos colgaban de la solicitud, y el
   anteproyecto pide un formulario por pieza (tipo de trabajo, material y
   acabado) con varias piezas por proyecto. Queda asi:

     SOLICITUDES 1--N SOLICITUD_PIEZAS 1--N SOLICITUD_MEDIDAS
                                       1--N SOLICITUD_ADJUNTOS (croquis y fotos)

   - SOLICITUD_PIEZAS nueva, con tipo de trabajo, tipo de material y acabado.
   - SOLICITUD_MEDIDAS y SOLICITUD_ADJUNTOS pasan de SOLICITUD_ID a PIEZA_ID.
   - El tipo de trabajo sale de SOLICITUDES: va solo en la pieza. El de
     COTIZACIONES se queda, es de la cotizacion.
   - SOLICITUDES gana CLIENTE_CONTACTO_ID y NOMBRE_PROYECTO (paso 1 del movil).
   - Catalogos TIPOS_MATERIAL (clasifica MATERIALES) y ACABADOS. Nacen vacios:
     las listas se validan con Anovo en minuta y se cargan desde la pantalla.

   Las solicitudes que ya existen reciben una pieza cada una, con la
   descripcion y el tipo de trabajo que tenian; sus medidas y adjuntos pasan a
   esa pieza. No se pierde nada.

   Las claves foraneas de SOLICITUD_ID se crearon sin nombre (INTEG_nn): se
   buscan antes de quitar la columna, como en la migracion 23. Los indices
   manuales de esas columnas ya los quito la 24.

   Rompe el contrato: backend (entidades, repositorios y servicios de medidas
   y adjuntos), escritorio (evidencia de la cotizacion) y movil.

   Todo en ASCII.
   ============================================================================ */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 37: piezas de la solicitud') FROM RDB$DATABASE;

/* ----------------------------------------------------------------------------
   1. Catalogos
   ---------------------------------------------------------------------------- */
CREATE TABLE TIPOS_MATERIAL (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE         D_NOMBRE NOT NULL UNIQUE,
  ACTIVO         D_BOOLEANO,
  FECHA_CREACION D_TIMESTAMP
);

CREATE TABLE ACABADOS (
  ID             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  NOMBRE         D_NOMBRE NOT NULL UNIQUE,
  ACTIVO         D_BOOLEANO,
  FECHA_CREACION D_TIMESTAMP
);

ALTER TABLE MATERIALES ADD TIPO_MATERIAL_ID INTEGER;
ALTER TABLE MATERIALES ADD CONSTRAINT FK_MATERIALES_TIPO_MATERIAL
  FOREIGN KEY (TIPO_MATERIAL_ID) REFERENCES TIPOS_MATERIAL (ID);

/* ----------------------------------------------------------------------------
   2. Datos del paso 1 en la solicitud
   ---------------------------------------------------------------------------- */
ALTER TABLE SOLICITUDES ADD CLIENTE_CONTACTO_ID INTEGER;
ALTER TABLE SOLICITUDES ADD NOMBRE_PROYECTO D_NOMBRE;
ALTER TABLE SOLICITUDES ADD CONSTRAINT FK_SOLICITUDES_CONTACTO
  FOREIGN KEY (CLIENTE_CONTACTO_ID) REFERENCES CLIENTE_CONTACTOS (ID);

/* ----------------------------------------------------------------------------
   3. Piezas
   ---------------------------------------------------------------------------- */
CREATE TABLE SOLICITUD_PIEZAS (
  ID                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  SOLICITUD_ID       INTEGER NOT NULL,
  UUID_LOCAL         D_UUID NOT NULL UNIQUE,
  NOMBRE             D_NOMBRE NOT NULL,
  TIPO_TRABAJO_ID    INTEGER,
  TIPO_MATERIAL_ID   INTEGER,
  ACABADO_ID         INTEGER,
  ORDEN              SMALLINT DEFAULT 0 NOT NULL,
  FECHA_CREACION     D_TIMESTAMP,
  FECHA_MODIFICACION D_TIMESTAMP,
  OBJVERSION         D_VERSION,
  CONSTRAINT FK_PIEZAS_SOLICITUD     FOREIGN KEY (SOLICITUD_ID)     REFERENCES SOLICITUDES (ID),
  CONSTRAINT FK_PIEZAS_TIPO_TRABAJO  FOREIGN KEY (TIPO_TRABAJO_ID)  REFERENCES TIPOS_TRABAJO (ID),
  CONSTRAINT FK_PIEZAS_TIPO_MATERIAL FOREIGN KEY (TIPO_MATERIAL_ID) REFERENCES TIPOS_MATERIAL (ID),
  CONSTRAINT FK_PIEZAS_ACABADO       FOREIGN KEY (ACABADO_ID)       REFERENCES ACABADOS (ID)
);

ALTER TABLE SOLICITUD_MEDIDAS  ADD PIEZA_ID INTEGER;
ALTER TABLE SOLICITUD_ADJUNTOS ADD PIEZA_ID INTEGER;

COMMIT;

/* ----------------------------------------------------------------------------
   4. Una pieza por cada solicitud existente; medidas y adjuntos pasan a ella
   ---------------------------------------------------------------------------- */
INSERT INTO SOLICITUD_PIEZAS (SOLICITUD_ID, UUID_LOCAL, NOMBRE, TIPO_TRABAJO_ID)
  SELECT S.ID, LOWER(UUID_TO_CHAR(GEN_UUID())), LEFT(S.DESCRIPCION, 120), S.TIPO_TRABAJO_ID
    FROM SOLICITUDES S;

UPDATE SOLICITUD_MEDIDAS M
   SET PIEZA_ID = (SELECT P.ID FROM SOLICITUD_PIEZAS P WHERE P.SOLICITUD_ID = M.SOLICITUD_ID);

UPDATE SOLICITUD_ADJUNTOS A
   SET PIEZA_ID = (SELECT P.ID FROM SOLICITUD_PIEZAS P WHERE P.SOLICITUD_ID = A.SOLICITUD_ID);

COMMIT;

ALTER TABLE SOLICITUD_MEDIDAS  ALTER PIEZA_ID SET NOT NULL;
ALTER TABLE SOLICITUD_ADJUNTOS ALTER PIEZA_ID SET NOT NULL;
ALTER TABLE SOLICITUD_MEDIDAS  ADD CONSTRAINT FK_MEDIDAS_PIEZA
  FOREIGN KEY (PIEZA_ID) REFERENCES SOLICITUD_PIEZAS (ID);
ALTER TABLE SOLICITUD_ADJUNTOS ADD CONSTRAINT FK_ADJUNTOS_PIEZA
  FOREIGN KEY (PIEZA_ID) REFERENCES SOLICITUD_PIEZAS (ID);

COMMIT;

/* ----------------------------------------------------------------------------
   5. Fuera las columnas viejas
   ---------------------------------------------------------------------------- */
DROP VIEW V_SOLICITUD_ADJUNTOS;

SET TERM ^ ;

EXECUTE BLOCK AS
  DECLARE VARIABLE V_TABLA VARCHAR(63);
  DECLARE VARIABLE V_FK VARCHAR(63);
BEGIN
  FOR SELECT TRIM(RC.RDB$RELATION_NAME), TRIM(RC.RDB$CONSTRAINT_NAME)
        FROM RDB$RELATION_CONSTRAINTS RC
        JOIN RDB$INDEX_SEGMENTS S ON S.RDB$INDEX_NAME = RC.RDB$INDEX_NAME
       WHERE RC.RDB$RELATION_NAME IN ('SOLICITUD_MEDIDAS', 'SOLICITUD_ADJUNTOS')
         AND RC.RDB$CONSTRAINT_TYPE = 'FOREIGN KEY'
         AND S.RDB$FIELD_NAME = 'SOLICITUD_ID'
        INTO :V_TABLA, :V_FK
  DO
    EXECUTE STATEMENT 'ALTER TABLE ' || V_TABLA || ' DROP CONSTRAINT ' || V_FK;
END^

SET TERM ; ^

ALTER TABLE SOLICITUDES DROP CONSTRAINT FK_SOLICITUDES_TIPO_TRABAJO;

COMMIT;

ALTER TABLE SOLICITUD_MEDIDAS  DROP SOLICITUD_ID;
ALTER TABLE SOLICITUD_ADJUNTOS DROP SOLICITUD_ID;
ALTER TABLE SOLICITUDES        DROP TIPO_TRABAJO_ID;

COMMIT;

/* ----------------------------------------------------------------------------
   6. Vistas de lectura. V_SOLICITUD_ADJUNTOS conserva SOLICITUD_ID por la
   pieza, para que la consulta por solicitud siga igual.
   ---------------------------------------------------------------------------- */
CREATE VIEW V_SOLICITUD_ADJUNTOS AS
SELECT A.ID, P.SOLICITUD_ID, A.PIEZA_ID, A.UUID_LOCAL, A.TIPO, A.NOMBRE_ARCHIVO,
       A.MIME, A.TAMANO_BYTES, A.ACTIVO, A.FECHA_CREACION
  FROM SOLICITUD_ADJUNTOS A
  JOIN SOLICITUD_PIEZAS P ON P.ID = A.PIEZA_ID;

CREATE VIEW V_SOLICITUD_MEDIDAS AS
SELECT M.ID, P.SOLICITUD_ID, M.PIEZA_ID, M.UUID_LOCAL, M.CROQUIS_ID, M.ETIQUETA,
       M.TIPO_MEDIDA, M.VALOR, M.UNIDAD_MEDIDA, M.CANTIDAD, M.OBSERVACION,
       M.ORDEN, M.FECHA_CREACION
  FROM SOLICITUD_MEDIDAS M
  JOIN SOLICITUD_PIEZAS P ON P.ID = M.PIEZA_ID;

CREATE VIEW V_SOLICITUD_PIEZAS AS
SELECT P.ID, P.SOLICITUD_ID, P.UUID_LOCAL, P.NOMBRE, P.ORDEN,
       P.TIPO_TRABAJO_ID, T.NOMBRE AS TIPO_TRABAJO_NOMBRE,
       P.TIPO_MATERIAL_ID, M.NOMBRE AS TIPO_MATERIAL_NOMBRE,
       P.ACABADO_ID, A.NOMBRE AS ACABADO_NOMBRE,
       CAST((SELECT COUNT(*) FROM SOLICITUD_MEDIDAS X WHERE X.PIEZA_ID = P.ID) AS INTEGER) AS MEDIDAS,
       CAST((SELECT COUNT(*) FROM SOLICITUD_ADJUNTOS X
              WHERE X.PIEZA_ID = P.ID AND X.TIPO = 'foto' AND X.ACTIVO) AS INTEGER) AS FOTOS,
       CAST((SELECT COUNT(*) FROM SOLICITUD_ADJUNTOS X
              WHERE X.PIEZA_ID = P.ID AND X.TIPO = 'croquis' AND X.ACTIVO) AS INTEGER) AS CROQUIS,
       P.FECHA_CREACION, P.FECHA_MODIFICACION
  FROM SOLICITUD_PIEZAS P
  LEFT JOIN TIPOS_TRABAJO  T ON T.ID = P.TIPO_TRABAJO_ID
  LEFT JOIN TIPOS_MATERIAL M ON M.ID = P.TIPO_MATERIAL_ID
  LEFT JOIN ACABADOS       A ON A.ID = P.ACABADO_ID;

/* ----------------------------------------------------------------------------
   7. Disparadores (solo fechas y valores por defecto, regla de la 28)
   ---------------------------------------------------------------------------- */
SET TERM ^ ;

CREATE TRIGGER TR_SOLICITUD_PIEZAS_BU FOR SOLICITUD_PIEZAS ACTIVE BEFORE UPDATE POSITION 0 AS
BEGIN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP; END^

CREATE TRIGGER TR_SOLICITUD_PIEZAS_BI_DEF FOR SOLICITUD_PIEZAS ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.FECHA_CREACION IS NULL) THEN NEW.FECHA_CREACION = CURRENT_TIMESTAMP;
  IF (NEW.FECHA_MODIFICACION IS NULL) THEN NEW.FECHA_MODIFICACION = CURRENT_TIMESTAMP;
  IF (NEW.OBJVERSION IS NULL) THEN NEW.OBJVERSION = 0;
END^

CREATE TRIGGER TR_TIPOS_MATERIAL_BI_DEF FOR TIPOS_MATERIAL ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ACTIVO IS NULL) THEN NEW.ACTIVO = TRUE;
  IF (NEW.FECHA_CREACION IS NULL) THEN NEW.FECHA_CREACION = CURRENT_TIMESTAMP;
END^

CREATE TRIGGER TR_ACABADOS_BI_DEF FOR ACABADOS ACTIVE BEFORE INSERT POSITION 0 AS
BEGIN
  IF (NEW.ACTIVO IS NULL) THEN NEW.ACTIVO = TRUE;
  IF (NEW.FECHA_CREACION IS NULL) THEN NEW.FECHA_CREACION = CURRENT_TIMESTAMP;
END^

SET TERM ; ^

/* ----------------------------------------------------------------------------
   8. Permisos del backend
   ---------------------------------------------------------------------------- */
GRANT SELECT, INSERT, UPDATE, DELETE ON SOLICITUD_PIEZAS TO ROL_BACKEND;
GRANT SELECT, INSERT, UPDATE ON TIPOS_MATERIAL TO ROL_BACKEND;
GRANT SELECT, INSERT, UPDATE ON ACABADOS TO ROL_BACKEND;
GRANT SELECT ON V_SOLICITUD_ADJUNTOS TO ROL_BACKEND;
GRANT SELECT ON V_SOLICITUD_MEDIDAS TO ROL_BACKEND;
GRANT SELECT ON V_SOLICITUD_PIEZAS TO ROL_BACKEND;

