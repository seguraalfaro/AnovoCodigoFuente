/* ============================================================================
   Anovo - Migracion 46: auditoria de catalogos, sin DELETE y huella de fotos
   ----------------------------------------------------------------------------
   Lista B de la matriz de trazabilidad (15/10/2026):

   1. Auditoria de los catalogos maestros (RF-007, HU-05). Los precios, las
      categorias y las unidades ya se auditaban; MATERIALES, MANO_OBRA,
      MAQUINAS, TIPOS_TRABAJO, TIPOS_MATERIAL, ACABADOS y FORMAS_PAGO no. Igual
      que TR_UNIDADES_MEDIDA_AUD: sin usuario en la sesion, la escritura falla.
   2. Sin DELETE para ROL_BACKEND en USUARIOS, MATERIALES, MANO_OBRA y
      MAQUINAS (RF-009, HU-05): se inactivan, nunca se borran. La API ya no
      borraba; ahora tampoco lo permite la base.
   3. SOLICITUD_ADJUNTOS.HASH_SHA256 (RNF-008): la huella que calcula el movil
      y que el servidor comprueba al recibir la foto. Nula en las fotos que
      llegaron antes.

   Todo en ASCII.
   ============================================================================ */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT ID FROM USUARIOS WHERE CORREO = 'sistema@anovo.local'))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 46: auditoria de catalogos y huella de fotos') FROM RDB$DATABASE;

ALTER TABLE SOLICITUD_ADJUNTOS ADD HASH_SHA256 VARCHAR(64);
COMMENT ON COLUMN SOLICITUD_ADJUNTOS.HASH_SHA256 IS
  'SHA-256 en hexadecimal de la imagen, calculado en el movil y comprobado al recibirla.';

REVOKE DELETE ON USUARIOS FROM ROL_BACKEND;
REVOKE DELETE ON MATERIALES FROM ROL_BACKEND;
REVOKE DELETE ON MANO_OBRA FROM ROL_BACKEND;
REVOKE DELETE ON MAQUINAS FROM ROL_BACKEND;

COMMIT;

SET TERM ^ ;

CREATE TRIGGER TR_MATERIALES_AUD FOR MATERIALES
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_DETALLE VARCHAR(500);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  V_DETALLE = RDB$GET_CONTEXT('USER_SESSION', 'DETALLE');
  IF (INSERTING) THEN BEGIN V_ACCION = 'insertar';   V_ID = NEW.ID; END
  ELSE IF (UPDATING) THEN BEGIN V_ACCION = 'actualizar'; V_ID = NEW.ID; END
  ELSE BEGIN V_ACCION = 'borrar'; V_ID = OLD.ID; END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'MATERIALES', :V_ID, :V_DETALLE);
END^

