  BEGIN
    V_ACCION = 'actualizar';
    V_ID = NEW.ID;
    V_DET = 'estado ' || OLD.ESTADO || ' -> ' || NEW.ESTADO;
  END
  ELSE
  BEGIN
    V_ACCION = 'borrar';
    V_ID = OLD.ID;
    V_DET = 'estado ' || OLD.ESTADO;
