/* ============================================================================
   Anovo - Migracion 10: el detalle de la auditoria lo pone el servicio
   ----------------------------------------------------------------------------
   AUDITORIA.DETALLE quedaba nulo en casi todo: el disparador sabe que cambio
   una fila, pero no por que. Quien si lo sabe es el servicio, que conoce la
   intencion -una edicion de datos, una revocacion de consentimiento-.

   El servicio deja el texto en el contexto de sesion antes de escribir y el
   disparador lo recoge:

     RDB$SET_CONTEXT('USER_SESSION', 'DETALLE', 'Revocacion del consentimiento')

   La fila no se inserta desde la aplicacion a proposito: el disparador la pone
   igual y serian dos. Asi tampoco se pierde la auditoria si alguien escribe
   por otra via; lo unico que faltaria es el texto.

   Los disparadores que ya traian un detalle fijo -cambio de clave, la nota de
   la Ley 8968, precio, permiso- lo conservan como respaldo con COALESCE.

   El contexto vive mientras dure la conexion, y la conexion se reutiliza entre
   peticiones: el middleware lo limpia al terminar, junto con el usuario.
   ============================================================================ */

SET TERM ^ ;

CREATE OR ALTER TRIGGER TR_USUARIOS_AUD FOR USUARIOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_DETALLE VARCHAR(500);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  /* Lo deja el servicio antes de escribir; si no lo deja, queda nulo. */
  V_DETALLE = RDB$GET_CONTEXT('USER_SESSION', 'DETALLE');
  IF (INSERTING) THEN BEGIN V_ACCION = 'insertar';   V_ID = NEW.ID; END
  ELSE IF (UPDATING) THEN BEGIN V_ACCION = 'actualizar'; V_ID = NEW.ID; END
  ELSE BEGIN V_ACCION = 'borrar'; V_ID = OLD.ID; END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'USUARIOS', :V_ID, :V_DETALLE);
END^

