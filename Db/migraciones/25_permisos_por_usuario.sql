/* Anovo - Migracion 25: permisos por usuario sobre el rol base.
   Excepciones otorgado/quitado con motivo, ambito en USUARIOS y vistas
   para Usuarios y Roles. Todo en ASCII. */

SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID',
  (SELECT MIN(ID) FROM USUARIOS WHERE ROL_ID = 5 AND ACTIVO = TRUE))
  FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE',
  'migracion 25: ambito del rol') FROM RDB$DATABASE;

ALTER TABLE USUARIOS
  ADD AMBITO D_AMBITO DEFAULT 'negocio' NOT NULL;

COMMIT;

UPDATE USUARIOS SET AMBITO = 'administracion'
 WHERE ROL_ID IN (SELECT ID FROM ROLES WHERE AMBITO = 'administracion');

COMMIT;

ALTER TABLE USUARIOS
  ADD CONSTRAINT UQ_USUARIOS_ID_AMBITO UNIQUE (ID, AMBITO);
ALTER TABLE USUARIOS
  ADD CONSTRAINT FK_USUARIOS_ROL_AMBITO FOREIGN KEY (ROL_ID, AMBITO)
    REFERENCES ROLES (ID, AMBITO);

COMMENT ON COLUMN USUARIOS.AMBITO IS
  'Copia del ambito del rol. Decide que permisos puede recibir la persona.';

CREATE TABLE USUARIOS_PERMISOS (
  USUARIO_ID     INTEGER       NOT NULL,
  PERMISO_ID     INTEGER       NOT NULL,
  AMBITO         D_AMBITO      NOT NULL,
  TIPO           VARCHAR(10)   NOT NULL,
  MOTIVO         D_DESCRIPCION NOT NULL,
  FECHA_CREACION D_TIMESTAMP,
  CONSTRAINT PK_USUARIOS_PERMISOS PRIMARY KEY (USUARIO_ID, PERMISO_ID),
  CONSTRAINT CK_USUPERM_TIPO CHECK (TIPO IN ('otorgado', 'quitado')),
  CONSTRAINT FK_USUPERM_USUARIO FOREIGN KEY (USUARIO_ID, AMBITO)
    REFERENCES USUARIOS (ID, AMBITO),
  CONSTRAINT FK_USUPERM_PERMISO FOREIGN KEY (PERMISO_ID, AMBITO)
    REFERENCES PERMISOS (ID, AMBITO)
);

COMMENT ON TABLE USUARIOS_PERMISOS IS
  'Excepciones de una persona sobre los permisos de su rol. Insert o delete, sin update.';

COMMIT;

SET TERM ^ ;

CREATE TRIGGER TR_USUARIOS_PERMISOS_AUD FOR USUARIOS_PERMISOS
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_PERMISO INTEGER;
  DECLARE VARIABLE V_TIPO    VARCHAR(10);
  DECLARE VARIABLE V_DETALLE VARCHAR(500);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  V_DETALLE = RDB$GET_CONTEXT('USER_SESSION', 'DETALLE');
  IF (INSERTING) THEN BEGIN V_ACCION = 'insertar';   V_ID = NEW.USUARIO_ID; V_PERMISO = NEW.PERMISO_ID; V_TIPO = NEW.TIPO; END
  ELSE IF (UPDATING) THEN BEGIN V_ACCION = 'actualizar'; V_ID = NEW.USUARIO_ID; V_PERMISO = NEW.PERMISO_ID; V_TIPO = NEW.TIPO; END
  ELSE BEGIN V_ACCION = 'borrar'; V_ID = OLD.USUARIO_ID; V_PERMISO = OLD.PERMISO_ID; V_TIPO = OLD.TIPO; END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'USUARIOS_PERMISOS', :V_ID,
          COALESCE(:V_DETALLE, :V_TIPO || ' permiso ' || :V_PERMISO));
END^

SET TERM ; ^

CREATE VIEW V_USUARIOS AS
SELECT U.ID, U.CORREO, U.NOMBRE, U.ROL_ID, R.CODIGO AS ROL,
       R.NOMBRE AS ROL_NOMBRE, U.AMBITO, U.ACTIVO, U.DEBE_CAMBIAR_CLAVE,
       U.FECHA_CREACION, U.FECHA_MODIFICACION,
       (SELECT MAX(C.FECHA_CAMBIO) FROM USUARIOS_CLAVES C
         WHERE C.USUARIO_ID = U.ID AND C.ACTIVO = TRUE) AS FECHA_CLAVE,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM USUARIOS_PERMISOS P
         WHERE P.USUARIO_ID = U.ID) AS EXCEPCIONES
  FROM USUARIOS U
  JOIN ROLES R ON R.ID = U.ROL_ID;

CREATE VIEW V_ROLES AS
SELECT R.ID, R.CODIGO, R.NOMBRE, R.AMBITO,
       (SELECT CAST(COUNT(*) AS INTEGER) FROM USUARIOS U
         WHERE U.ROL_ID = R.ID AND U.ACTIVO = TRUE) AS USUARIOS_ACTIVOS
  FROM ROLES R;

CREATE VIEW V_USUARIOS_PERMISOS AS
SELECT UP.USUARIO_ID, UP.PERMISO_ID, P.CODIGO AS PERMISO, P.NOMBRE,
       P.MODULO, UP.TIPO, UP.MOTIVO, UP.FECHA_CREACION
  FROM USUARIOS_PERMISOS UP
  JOIN PERMISOS P ON P.ID = UP.PERMISO_ID;

COMMIT;

GRANT SELECT, INSERT, DELETE ON USUARIOS_PERMISOS TO ROL_BACKEND;
GRANT SELECT ON V_USUARIOS          TO ROL_BACKEND;
GRANT SELECT ON V_ROLES             TO ROL_BACKEND;
GRANT SELECT ON V_USUARIOS_PERMISOS TO ROL_BACKEND;

GRANT INSERT ON AUDITORIA TO TRIGGER TR_USUARIOS_PERMISOS_AUD;
GRANT USAGE ON EXCEPTION E_AUDITORIA_SIN_USUARIO TO TRIGGER TR_USUARIOS_PERMISOS_AUD;

SELECT RDB$SET_CONTEXT('USER_SESSION', 'DETALLE', NULL) FROM RDB$DATABASE;
SELECT RDB$SET_CONTEXT('USER_SESSION', 'USUARIO_ID', NULL) FROM RDB$DATABASE;

COMMIT;
