/* ============================================================================
   Anovo - Migracion 11: las categorias de mano de obra dejan de ser cerradas
   ----------------------------------------------------------------------------
   MANO_OBRA_CATEGORIA se diseno como catalogo cerrado: seis filas sembradas a
   mano en 02_datos.sql, ID sin autogenerar, sin ACTIVO y sin auditoria -asi
   esta anotado en la cabecera de 03_auditoria.sql-. Se abre para que el
   supervisor pueda registrar categorias desde la aplicacion, como ya hace con
   materiales, mano de obra y maquinas.

   POR QUE UN GENERADOR Y NO IDENTITY

   Lo natural seria volver la columna autogenerada, como en las demas tablas.
   Firebird 4.0.6 no lo permite sobre una columna que ya existe. Comprobado
   sobre una base de prueba: las tres formas fallan.

     ALTER TABLE CAT ALTER ID SET GENERATED BY DEFAULT AS IDENTITY;
     ALTER TABLE CAT ALTER COLUMN ID SET GENERATED BY DEFAULT AS IDENTITY;
     ALTER TABLE CAT ALTER ID GENERATED BY DEFAULT AS IDENTITY;

     -SQL error code = -104
     -Token unknown - AS

   La alternativa es recrear la tabla, pero MANO_OBRA.CATEGORIA_ID la
   referencia: habria que soltar y rehacer la clave foranea sobre datos vivos.
   Un generador con disparador BEFORE INSERT da el mismo resultado sin tocar la
   estructura, y es lo que el proyecto ya usa para el consecutivo de las
   cotizaciones.

   El backend no se entera: el generador de SQL de Firebird de DMVC agrega
   RETURNING a la insercion cuando la clave es autogenerada, asi que el numero
   vuelve solo. Lo unico por ajustar a mano es el atributo de la entidad, que
   MVCEntGen no marca como autogenerada porque en el catalogo del sistema la
   columna sigue siendo una INTEGER comun:

     [MVCTableField('ID', [foPrimaryKey, foAutoGenerated])]

   CODIGO sigue siendo UNIQUE y NOT NULL: quien registre una categoria tiene
   que darle uno, como las seis que ya estan.
   ============================================================================ */

/* ----------------------------------------------------------------------------
   1. ACTIVO. Nada se borra en este sistema: una categoria que ya no se usa se
   inactiva, y la mano de obra que la nombra sigue teniendo sentido.

   El dominio trae DEFAULT TRUE NOT NULL, asi que las seis filas sembradas
   quedan activas sin tener que actualizarlas.
   ---------------------------------------------------------------------------- */
ALTER TABLE MANO_OBRA_CATEGORIA ADD ACTIVO D_BOOLEANO;

/* ----------------------------------------------------------------------------
   2. El generador. Arranca en 7, que es el primer numero libre despues de las
   seis filas de 02_datos.sql.

   RESTART WITH 7 y no 6: en Firebird 4 el valor que se indica es el que
   devuelve el PRIMER NEXT VALUE, no el ultimo entregado. Comprobado -con 6 la
   insercion choca contra la clave primaria de la fila 'acabado'-.
   ---------------------------------------------------------------------------- */
CREATE SEQUENCE GEN_MANO_OBRA_CATEGORIA;
ALTER SEQUENCE GEN_MANO_OBRA_CATEGORIA RESTART WITH 7;

COMMIT;

SET TERM ^ ;

/* ----------------------------------------------------------------------------
   3. El id, cuando no viene. Va en POSITION 0, antes del de auditoria, y solo
   actua si el ID llega nulo: una carga que traiga numeros propios -otra
   siembra, una restauracion- los conserva.
   ---------------------------------------------------------------------------- */
CREATE TRIGGER TR_MANO_OBRA_CATEGORIA_BI FOR MANO_OBRA_CATEGORIA
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = NEXT VALUE FOR GEN_MANO_OBRA_CATEGORIA;
END^

/* ----------------------------------------------------------------------------
   4. La auditoria, igual que la de los demas catalogos: el usuario sale del
   contexto de sesion que fija el middleware, y sin usuario la escritura falla
   en vez de registrarse como anonima.

   El detalle lo deja el servicio antes de escribir; si no lo deja, queda nulo.
   ---------------------------------------------------------------------------- */
CREATE TRIGGER TR_MANO_OBRA_CATEGORIA_AUD FOR MANO_OBRA_CATEGORIA
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 10
AS
  DECLARE VARIABLE V_USUARIO INTEGER;
  DECLARE VARIABLE V_ACCION  VARCHAR(50);
  DECLARE VARIABLE V_ID      INTEGER;
  DECLARE VARIABLE V_DETALLE VARCHAR(500);
BEGIN
  V_USUARIO = CAST(RDB$GET_CONTEXT('USER_SESSION', 'USUARIO_ID') AS INTEGER);
  IF (V_USUARIO IS NULL) THEN EXCEPTION E_AUDITORIA_SIN_USUARIO;
  V_DETALLE = RDB$GET_CONTEXT('USER_SESSION', 'DETALLE');
  IF (INSERTING) THEN BEGIN V_ACCION = 'insertar';   V_ID = NEW.ID; END
  ELSE IF (UPDATING) THEN BEGIN V_ACCION = 'actualizar'; V_ID = NEW.ID; END
  ELSE BEGIN V_ACCION = 'borrar'; V_ID = OLD.ID; END
  INSERT INTO AUDITORIA (USUARIO_ID, ACCION, ENTIDAD, ENTIDAD_ID, DETALLE)
  VALUES (:V_USUARIO, :V_ACCION, 'MANO_OBRA_CATEGORIA', :V_ID, :V_DETALLE);
END^

SET TERM ; ^

COMMIT;

/* ----------------------------------------------------------------------------
   5. Los permisos del disparador. En Firebird 4 las rutinas corren como
   SQL SECURITY INVOKER, o sea con los privilegios de ANOVO_BACKEND, a quien se
   le retiro todo sobre AUDITORIA. Sin estos dos GRANT la primera escritura
   muere con "no permission for INSERT access to TABLE AUDITORIA", y el segundo
   hace falta porque lanzar una excepcion con nombre tambien exige USAGE.
   ---------------------------------------------------------------------------- */
GRANT INSERT ON AUDITORIA TO TRIGGER TR_MANO_OBRA_CATEGORIA_AUD;
GRANT USAGE ON EXCEPTION E_AUDITORIA_SIN_USUARIO TO TRIGGER TR_MANO_OBRA_CATEGORIA_AUD;

/* ----------------------------------------------------------------------------
   6. El generador lo usa el disparador, que corre como el invocador.
   ---------------------------------------------------------------------------- */
GRANT USAGE ON SEQUENCE GEN_MANO_OBRA_CATEGORIA TO TRIGGER TR_MANO_OBRA_CATEGORIA_BI;

/* ----------------------------------------------------------------------------
   7. El backend podia leer esta tabla y nada mas, porque era un catalogo
   cerrado. Abrirla sin esto la deja sin escribir: la primera insercion muere
   con "no permission for INSERT access to TABLE MANO_OBRA_CATEGORIA".

   Sin DELETE, aunque los otros catalogos lo tengan: aqui nada se borra, una
   categoria que ya no se usa se inactiva con la columna del paso 1.
   ---------------------------------------------------------------------------- */
GRANT INSERT, UPDATE ON MANO_OBRA_CATEGORIA TO ROL_BACKEND;

COMMIT;

